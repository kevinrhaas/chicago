const STREET_NAME = { prairie: 'Prairie Avenue', indiana: 'Indiana Avenue', calumet: 'Calumet Avenue' };
export function lotWhere(lot) {
  const adds = lot.addresses ?? [];
  const a = adds.length > 1 ? `${adds[0]}–${adds.at(-1)} ` : adds.length ? `${adds[0]} ` : '';
  const street = STREET_NAME[lot.street] ?? `East ${String(lot.street ?? '').replace(/^e/, '')} Street`;
  return `${a}${street}`;
}
function article(words) { return /^[aeiou]/i.test(words) ? 'An' : 'A'; }
function sentence(s) {
  const t = String(s ?? '').trim();
  if (!t) return '';
  return /[.!?]$/.test(t) ? t : `${t}.`;
}

/**
 * A card for a hit: { lot, what: 'surface'|'door'|'post'|'crop', index, item }, in the same
 * shape the front yards' cards take (popup.js reads the sidecar).
 */
export function backYardCard(hit, doc) {
  const { lot, what, index, item } = hit;
  const where = lotWhere(lot);
  const grade = item?.grade ?? lot.grade ?? 'reconstructed';
  const liberty = doc?.liberty ?? '';
  const sources = grade === 'reconstructed' ? [] : [...new Set([...(item?.sources ?? []), ...(lot.sources ?? [])])];
  let name; let kindWords; let materialLabel = '';
  if (what === 'surface') {
    kindWords = doc?.kinds?.[item.kind] ?? KIND_WORDS[item.kind] ?? String(item.kind ?? 'yard surface').replace(/_/g, ' ');
    materialLabel = doc?.materials?.[item.material]?.label ?? String(item.material ?? '').replace(/_/g, ' ');
    const cap = kindWords[0].toUpperCase() + kindWords.slice(1);
    name = materialLabel ? `${cap}, ${materialLabel}` : cap;
  } else if (what === 'door') {
    const stoop = item.stoop ? (item.stoop.material === 'stone' ? 'stone steps' : 'wooden steps') : '';
    kindWords = item.leaf === false ? 'back steps' : 'back door';
    materialLabel = stoop;
    name = item.leaf === false ? `The back steps, ${stoop || 'to the rear door'}`
      : `The back door${stoop ? ` and its ${stoop}` : ''}`;
  } else if (what === 'post') {
    kindWords = 'clothes post';
    materialLabel = 'a timber post with its cross arm';
    name = 'A clothes post in the drying yard';
  } else {
    kindWords = 'kitchen garden';
    const crop = String(item.kind ?? 'vegetables').replace(/_/g, ' ');
    materialLabel = `a row of ${crop}`;
    name = `${article(crop)} ${crop} row in the kitchen garden`;
  }
  const scheme = SCHEME_WORDS[lot.scheme] ?? '';
  const lead = `Behind ${where}${scheme ? `, ${scheme}` : ''}: the ${kindWords}${materialLabel && what === 'surface' ? ` in ${materialLabel}` : ''}.`;
  const change = [lead, sentence(lot.note), sentence(item?.note)].filter(Boolean).join(' ');
  const gradeWords = grade === 'reconstructed'
    ? `Reconstructed: no record shows this yard's ${kindWords}; it is laid as the period's yards were (${liberty}).`
    : grade === 'inferred' ? `Inferred: ${sentence(item?.note || lot.note) || 'read from what the sources say of the lot.'}`
      : `Attested: ${sentence(item?.note || lot.note) || 'a source shows it.'}`;
  const id = `back-yard.${lot.parcel}.${what}.${index}`;
  return {
    id,
    sidecar: {
      name,
      phase: null,
      change_note: change,
      placement: {
        symbolic_location: `behind ${where}`,
        position_confidence: grade,
        position_sources: sources,
        position_note: grade === 'reconstructed' ? `Laid by ${doc?.generated_by ?? 'the back-yard layout'}; ${liberty}`.trim() : sentence(item?.note || lot.note),
      },
      attributes: {
        kind: { value: kindWords, confidence: grade, sources, note: gradeWords },
        ...(materialLabel ? { material: { value: materialLabel, confidence: grade, sources, note: gradeWords } } : {}),
      },
      citations: [],
      research_doc: 'docs/RESEARCH/prairie_1904_back_yards.md',
      research_note: `Lot ${lot.parcel} of data/back_yards/${doc?.scene ?? '1904'}.json (${doc?.ticket ?? 'T-3488'}), `
        + `the ${kindWords} (${grade}). Liberty ${liberty || 'none named'}.`,
    },
  };
}

