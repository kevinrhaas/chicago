class FixtureBuf {
  /** `uTile` (metres): lay a uv on every face, u along its longer edge in tiles of uTile, v
   *  0..1 across its shorter (the dressed-stone map: its arrises at each face's edges). */
  constructor(uTile = null) {
    this.pos = []; this.nor = []; this.col = []; this.conf = []; this.idx = []; this.boxes = 0;
    this.uTile = uTile; this.uv = uTile ? [] : null;
  }
  get vertexCount() { return this.pos.length / 3; }
  quad(p, nrm, c, k) {
    const base = this.pos.length / 3;
    for (const q of p) { this.pos.push(q[0], q[1], q[2]); this.nor.push(nrm[0], nrm[1], nrm[2]); this.col.push(c.r, c.g, c.b); this.conf.push(k); }
    if (this.uv) {
      const L = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
      const la = L(p[0], p[1]); const lb = L(p[0], p[3]);
      // a few-centimetre offset per face so neighbouring stones do not repeat the same grain
      const o = hash(Math.round(p[0][0] * 37), Math.round(p[0][2] * 41)) * 3;
      if (la >= lb) this.uv.push(o, 0, o + la / this.uTile, 0, o + la / this.uTile, 1, o, 1);
      else this.uv.push(o, 0, o, 1, o + lb / this.uTile, 1, o + lb / this.uTile, 0);
    }
    this.idx.push(base, base + 1, base + 2, base, base + 2, base + 3);
  }
  /** A hexahedron from its eight world corners: [x0y0z0, x1y0z0, x1y0z1, x0y0z1] bottom then the
   *  same top (x, z as named in the caller's frame); faces with outward normals. */
  hexa(c, colour, k, { bottom = false } = {}) {
    const col = colour instanceof THREE.Color ? colour : new THREE.Color(colour);
    const faces = [[0, 1, 2, 3, true], [4, 7, 6, 5, false], [0, 4, 5, 1], [1, 5, 6, 2], [2, 6, 7, 3], [3, 7, 4, 0]];
    const centre = c.reduce((a, p) => [a[0] + p[0] / 8, a[1] + p[1] / 8, a[2] + p[2] / 8], [0, 0, 0]);
    for (const f of faces) {
      if (f[4] === true && !bottom) continue;
      const q = [c[f[0]], c[f[1]], c[f[2]], c[f[3]]];
      const u = new THREE.Vector3(...q[1]).sub(new THREE.Vector3(...q[0]));
      const v = new THREE.Vector3(...q[3]).sub(new THREE.Vector3(...q[0]));
      const nrm = new THREE.Vector3().crossVectors(u, v);
      if (nrm.lengthSq() < 1e-14) {
        nrm.crossVectors(new THREE.Vector3(...q[2]).sub(new THREE.Vector3(...q[1])), new THREE.Vector3(...q[0]).sub(new THREE.Vector3(...q[1])));
      }
      nrm.normalize();
      const mid = new THREE.Vector3(...q[0]).add(new THREE.Vector3(...q[2])).multiplyScalar(0.5);
      // outward: away from the solid's centre (a degenerate wedge keeps its sense)
      let quad = q;
      if (nrm.dot(mid.sub(new THREE.Vector3(...centre))) < 0) { nrm.negate(); quad = [q[0], q[3], q[2], q[1]]; }
      this.quad(quad, [nrm.x, nrm.y, nrm.z], col, k);
    }
    this.boxes += 1;
  }
  geometry() {
    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.Float32BufferAttribute(this.pos, 3));
    // compact: a box's normals are unit axes and its paint a byte a channel (about half the bytes)
    geo.setAttribute('normal', new THREE.BufferAttribute(Int8Array.from(this.nor, (v) => Math.round(v * 127)), 3, true));
    geo.setAttribute('color', new THREE.BufferAttribute(Uint8Array.from(this.col, (v) => Math.round(Math.min(1, Math.max(0, v)) * 255)), 3, true));
    geo.setAttribute('_confidence', new THREE.Float32BufferAttribute(this.conf, 1));
    if (this.uv) geo.setAttribute('uv', new THREE.Float32BufferAttribute(this.uv, 2));
    const n = this.pos.length / 3;
    geo.setIndex(n > 65535 ? new THREE.Uint32BufferAttribute(this.idx, 1) : new THREE.Uint16BufferAttribute(this.idx, 1));
    geo.computeBoundingSphere();
    return geo;
  }
}

/**
 * A plan frame at a point: `o` the unit plan vector a bearing points along (out of the
 * house), `t` the one 90 degrees clockwise of it (along the wall, to the right of a visitor
 * coming in). `at(s, w, y)` is the world point s out, w along, at height y.
 */
export function frameAt(e, n, bearingDeg) {
  const th = (Number(bearingDeg) || 0) * Math.PI / 180;
  const o = [Math.sin(th), Math.cos(th)];
  const t = [Math.cos(th), -Math.sin(th)];
  const at = (s, w, y) => {
    const pe = e + o[0] * s + t[0] * w; const pn = n + o[1] * s + t[1] * w;
    return [pe, y, -pn];
  };
  const plan = (s, w) => [e + o[0] * s + t[0] * w, n + o[1] * s + t[1] * w];
  return { o, t, at, plan };
}

/** An axis box in a frame: s (out) from s0 to s1, w (along) w0 to w1, y0 to y1. */
function frameBox(buf, f, s0, s1, w0, w1, y0, y1, colour, k, opts) {
  buf.hexa([
    f.at(s0, w0, y0), f.at(s1, w0, y0), f.at(s1, w1, y0), f.at(s0, w1, y0),
    f.at(s0, w0, y1), f.at(s1, w0, y1), f.at(s1, w1, y1), f.at(s0, w1, y1),
  ], colour, k, opts);
}
/** A sloped member in a frame: its section `w0..w1` wide and `d` deep (vertically), its top
 *  edge running from (sA, yA) to (sB, yB). */
function frameSlope(buf, f, sA, yA, sB, yB, w0, w1, d, colour, k) {
  buf.hexa([
    f.at(sA, w0, yA - d), f.at(sB, w0, yB - d), f.at(sB, w1, yB - d), f.at(sA, w1, yA - d),
    f.at(sA, w0, yA), f.at(sB, w0, yB), f.at(sB, w1, yB), f.at(sA, w1, yA),
  ], colour, k, { bottom: true });
}

/** A colour a touch off its paint, so no two boards read as one moulding. */
function varied(hex, seed, amount = 0.06) {
  const c = new THREE.Color(hex);
  const j = 1 + (hash(Math.round(seed * 1e5), 7) - 0.5) * 2 * amount;
  return c.multiplyScalar(j);
}

/**
 * The stoop's numbers, from the sill down to the ground at its foot: how many risers, each
 * one's rise, the landing's top and each tread's top and going. Exported for the test.
 *   sillY   the door's sill, world y; footY the ground where the last tread lands.
 */
export function stoopPlan(sillY, footY, depthM, wantRisers = null) {
  const H = Math.max(0, sillY - footY);
  // the file's own count where it gives one (the layout tool's `risers`); else ~RISE_M a riser
  const risers = H < RISE_M * 0.5 ? 0
    : Number.isInteger(wantRisers) && wantRisers > 0 ? wantRisers : Math.max(1, Math.round(H / RISE_M));
  const rise = risers ? H / risers : 0;
  const treads = [];
  // the landing is the top tread; each step below it one rise down and one tread out
  for (let k = 1; k < risers; k += 1) {
    treads.push({ top: sillY - k * rise, s0: depthM + (k - 1) * TREAD_M, s1: depthM + k * TREAD_M });
  }
  return { H, risers, rise, landingTop: sillY, treads, run: depthM + Math.max(0, risers - 1) * TREAD_M, rail: H > RAIL_RISE_M };
}

/** The door's leaf, casing and sill on the wall face (s = 0 is the face; s > 0 is out). With
 *  `casing` false only the leaf; with `leaf` false the casing, the sill and the dark doorway
 *  the leaf shuts over (T-3554: a passage's leaf is drawn on its hinge, `doorLeafGeometry`). */
function buildDoorLeaf(buf, f, d, sillY, k, light, stone = { buf, tone: PAINT.sill }, { leaf = true, casing = true } = {}) {
  const W = d.width_m ?? 0.95; const Hh = d.height_m ?? 2.2;
  const hw = W / 2; const cw = 0.11; const cd = 0.055;
  if (casing) {
    // the stone sill, a little proud of the wall and past the jambs
    frameBox(stone.buf, f, -0.02, 0.07, -hw - cw - 0.04, hw + cw + 0.04, sillY - 0.06, sillY, varied(stone.tone, 9, 0.03), k);
    // the casing: two jambs and the head (no transom)
    frameBox(buf, f, 0, cd, -hw - cw, -hw, sillY, sillY + Hh + cw, PAINT.casing, k);
    frameBox(buf, f, 0, cd, hw, hw + cw, sillY, sillY + Hh + cw, PAINT.casing, k);
    frameBox(buf, f, 0, cd + 0.01, -hw - cw - 0.02, hw + cw + 0.02, sillY + Hh, sillY + Hh + cw + 0.03, PAINT.casing, k);
    // the dark of the doorway, on the wall behind the leaf: what shows when it stands open
    if (!leaf) frameBox(buf, f, 0, 0.004, -hw, hw, sillY, sillY + Hh, PAINT.doorway, k);
  }
  if (!leaf) return;
  // the leaf, set back in its casing
  const lf = 0.025;
  frameBox(buf, f, 0, lf, -hw, hw, sillY, sillY + Hh, PAINT.leaf, k);
  if (!light) {
    // stiles and rails stand proud of the panels: the glazed upper light and two panels below
    const st = 0.12; const rl = 0.13;
    const glassTop = sillY + Hh - rl; const glassBot = sillY + Hh * 0.52;
    const lockRail = glassBot - 0.16;
    const proud = lf + 0.014;
    frameBox(buf, f, lf, proud, -hw, -hw + st, sillY, sillY + Hh, varied(PAINT.leaf, 1), k);
    frameBox(buf, f, lf, proud, hw - st, hw, sillY, sillY + Hh, varied(PAINT.leaf, 2), k);
    frameBox(buf, f, lf, proud, -hw + st, hw - st, glassTop, sillY + Hh, varied(PAINT.leaf, 3), k);
    frameBox(buf, f, lf, proud, -hw + st, hw - st, lockRail, glassBot, varied(PAINT.leaf, 4), k);
    frameBox(buf, f, lf, proud, -hw + st, hw - st, sillY, sillY + 0.22, varied(PAINT.leaf, 5), k);
    frameBox(buf, f, lf, lf + 0.004, -hw + st, hw - st, glassBot, glassTop, PAINT.glass, k);
    // the muntin across the light, the panels' muntin, and the knob
    frameBox(buf, f, lf, proud, -0.02, 0.02, glassBot, glassTop, varied(PAINT.leaf, 6), k);
    frameBox(buf, f, lf, proud, -0.05, 0.05, sillY + 0.22, lockRail, varied(PAINT.leaf, 7), k);
    frameBox(buf, f, proud, proud + 0.06, hw - st + 0.02, hw - st + 0.07, sillY + 0.95, sillY + 1.0, PAINT.knob, k);
  } else {
    frameBox(buf, f, lf, lf + 0.004, -hw + 0.12, hw - 0.12, sillY + Hh * 0.52, sillY + Hh - 0.13, PAINT.glass, k);
  }
}

/** How far a back door's leaf swings out (degrees) and how long it takes (s). Ours. */
export const BACK_DOOR_OPEN_DEG = 95;
export const BACK_DOOR_SWING_S = 1.2;
/** Where one waits for the leaf to swing out past them, out from the face (its sweep at the
 *  door's middle is under 0.85 m), and how far in they are when they are indoors. */
const BACK_DOOR_WAIT_M = 0.95;
const BACK_DOOR_IN_M = 0.6;
const BACK_DOOR_STEP_M = 0.7;
const BACK_DOOR_EASE_M = 0.12;

/** A back door's leaf in its hinge's frame: x along the shut leaf from the hinge (its jamb
 *  at w = -W/2) to its free edge, y up from the sill, -z out of the house. */
export function doorLeafGeometry(d, k, light) {
  const buf = new FixtureBuf();
  buildDoorLeaf(buf, frameAt(0, 0, 0), d, 0, k, light, undefined, { casing: false });
  const geo = buf.geometry();
  geo.translate((d.width_m ?? 0.95) / 2, 0, 0);
  geo.computeBoundingSphere();
  return geo;
}

/**
 * T-3554: the way in by a back door, outside to in, along the door's middle: [{ s, y }] with s
 * out from the wall face and y the world height (null on the ground), from STEP out beyond the
 * stoop's foot up every tread (each riser eased BACK_DOOR_EASE_M either side) onto the landing
 * to BACK_DOOR_WAIT_M out (`door`, where one waits for the leaf), over the sill and
 * BACK_DOOR_IN_M in. `p` is the stoop's plan (stoopPlan) or null, `depth` its landing's.
 */
export function backDoorWay(sillY, p, depth) {
  const heightAt = (s) => {
    if (s <= 0) return sillY;
    if (!p || !p.risers) return s <= 0.3 ? sillY : null;
    if (s <= depth) return sillY;
    for (const t of p.treads) if (s >= t.s0 && s <= t.s1) return t.top;
    return null;
  };
  const run = p?.risers ? p.run : 0.3;
  const out = [];
  const push = (s, y) => { if (!out.length || Math.abs(out.at(-1).s - s) > 1e-4) out.push({ s, y }); };
  push(run + BACK_DOOR_STEP_M, null);
  // every riser between, walked inward
  const edges = [...new Set([run, ...(p?.treads ?? []).flatMap((t) => [t.s0, t.s1]), depth])].filter((s) => s > BACK_DOOR_WAIT_M && s <= run)
    .sort((a, b) => b - a);
  for (const e of edges) {
    const before = heightAt(e + 0.01), after = heightAt(e - 0.01);
    if (before === after) continue;
    push(e + BACK_DOOR_EASE_M, before);
    push(e - BACK_DOOR_EASE_M, after);
  }
  push(BACK_DOOR_WAIT_M, heightAt(BACK_DOOR_WAIT_M));
  const door = out.length - 1;
  push(0, sillY);
  push(-BACK_DOOR_IN_M, sillY);
  out.door = door;
  return out;
}

/**
 * The owner, 2026-11-14: "Anywhere there are stairs I should be able to climb". A back stoop as
 * walker decks (house-floors.js mergeDecks files them): its landing and treads, at the tops
 * buildStoop draws them, a tread at a time; and, where it has rails, a wall along each (a metre
 * over the landing, past any step), so one climbs between them rather than through them.
 * `f` is the door's frame (frameAt), `p` the stoop's plan (stoopPlan).
 */
export function stoopDecks(id, f, d, sillY, p) {
  if (!p) return [];
  const st = d.stoop ?? {};
  const depth = (st.depth_m ?? 1.2) >= 0.05 ? st.depth_m ?? 1.2 : TREAD_M;
  const hw = Math.max(d.width_m ?? 0.95, st.width_m ?? 1.6) / 2;
  const top = sillY - 0.012;
  const run = Math.max(depth, p.run);
  const [e0, n0] = f.plan(0, 0);
  const rect = (s0, s1, w0, w1) => [[s0, w0], [s1, w0], [s1, w1], [s0, w1]].map(([s, w]) => f.plan(s, w));
  const heightAt = (e, n) => {
    const de = e - e0, dn = n - n0;
    const s = de * f.o[0] + dn * f.o[1], w = de * f.t[0] + dn * f.t[1];
    if (s < -0.02 || s > run || Math.abs(w) > hw) return null;
    if (s <= depth) return top;
    for (const t of p.treads) if (s >= t.s0 - 1e-6 && s <= t.s1 + 1e-6) return t.top;
    return null;
  };
  const out = [{ id: `${id}:stoop`, y: Math.min(top, ...p.treads.map((t) => t.top)), pts: rect(-0.02, run, -hw, hw), heightAt }];
  if (p.rail) {
    for (const side of [-1, 1]) {
      const w = side * (hw - 0.045);
      out.push({ id: `${id}:rail${side < 0 ? 'L' : 'R'}`, y: top + 1, pts: rect(0, run - TREAD_M * 0.5, w - 0.06, w + 0.06), wall: true });
    }
  }
  return out;
}

/** The stoop from the wall out: landing, steps, and (over RAIL_RISE_M) the rails. */
function buildStoop(buf, f, d, sillY, groundAt, k, light, stoneBuf = { buf, tone: PAINT.stone }) {
  const st = d.stoop ?? {};
  // depth 0: no landing (the layout tool's stoops of under three risers), the sill the top step
  // depth 0 (the layout tool's stoops of under three risers): the top step is a stone or a
  // board one tread deep at the sill, which is what its `run_m` counts
  const depth = (st.depth_m ?? 1.2) >= 0.05 ? st.depth_m ?? 1.2 : TREAD_M;
  const landing = true;
  const width = Math.max(d.width_m ?? 0.95, st.width_m ?? 1.6);
  const hw = width / 2;
  // the ground at the foot of the flight: sampled where the last tread would land
  const first = stoopPlan(sillY, groundAt(...f.plan(depth, 0)), depth, st.risers);
  const footPlan = f.plan(first.run + TREAD_M * 0.5, 0);
  const footY = Math.min(groundAt(...footPlan), groundAt(...f.plan(depth, 0)));
  const p = stoopPlan(sillY, footY, depth, st.risers);
  const below = footY - 0.08; // footings run a little under the sward
  const stone = st.material === 'stone';
  const top = sillY - 0.012;  // the landing a hair under the sill's top
  if (stone) {
    // a solid landing block and a solid block under each step, nosed over the one below
    // each block reaches a nosing past its own front, over the riser of the block below it
    if (landing) frameBox(stoneBuf.buf, f, 0, depth + (p.treads.length ? NOSING_M : 0), -hw, hw, below, top, varied(stoneBuf.tone, 11, 0.04), k);
    for (const [i, tr] of p.treads.entries()) {
      const last = i === p.treads.length - 1;
      frameBox(stoneBuf.buf, f, tr.s0, tr.s1 + (last ? 0 : NOSING_M), -hw, hw, below, tr.top, varied(stoneBuf.tone, 20 + i, 0.05), k);
    }
    if (p.rail) {
      const r = 0.018; const hRail = 0.86;
      for (const side of [-1, 1]) {
        const w = side * (hw - 0.07);
        // posts at the landing's outer corner and at the foot; the pipe along the flight
        frameBox(buf, f, depth - 0.08 - r, depth - 0.08 + r, w - r, w + r, top, top + hRail, PAINT.pipe, k);
        const sFoot = p.run - 0.1;
        const yFoot = (p.treads.at(-1)?.top ?? top);
        frameBox(buf, f, sFoot - r, sFoot + r, w - r, w + r, yFoot, yFoot + hRail, PAINT.pipe, k);
        frameSlope(buf, f, depth - 0.08, top + hRail, sFoot, yFoot + hRail, w - r, w + r, 2 * r, PAINT.pipe, k);
        frameSlope(buf, f, 0.02, top + hRail, depth - 0.08, top + hRail, w - r, w + r, 2 * r, PAINT.pipe, k);
      }
    }
    return p;
  }
  // WOOD: a deck of boards running out from the wall over a skirt; treads on two stringers,
  // risers boarded; the boards gapped a few millimetres (full and balanced only).
  const deckT = 0.03;
  // the skirt boarded in under the deck, a hair under the boards (the gaps between them show it)
  if (landing) frameBox(buf, f, 0.02, depth - 0.03, -hw + 0.02, hw - 0.02, below, top - deckT - 0.004, PAINT.skirt, k);
  if (!landing) {
    // no deck: the sill is the top step
  } else if (light) {
    frameBox(buf, f, 0, depth + NOSING_M, -hw, hw, top - deckT, top, PAINT.deck, k);
  } else {
    const board = 0.095; const gap = 0.006;
    const nB = Math.max(2, Math.round(width / (board + gap)));
    const bw = width / nB;
    for (let i = 0; i < nB; i += 1) {
      const w0 = -hw + i * bw + gap / 2; const w1 = -hw + (i + 1) * bw - gap / 2;
      frameBox(buf, f, 0, depth + NOSING_M, w0, w1, top - deckT, top, varied(PAINT.deck, 100 + i), k);
    }
  }
  // stringers from under the landing's front to the foot
  if (p.treads.length) {
    const last = p.treads.at(-1);
    for (const side of [-1, 1]) {
      const w0 = side < 0 ? -hw - 0.006 : hw - 0.034; const w1 = side < 0 ? -hw + 0.034 : hw + 0.006;
      frameSlope(buf, f, Math.max(0.01, depth - 0.05), top - 0.02, last.s1 + 0.02, footY + 0.02, w0, w1, 0.24, PAINT.stringer, k);
    }
  }
  for (const [i, tr] of p.treads.entries()) {
    const riserTop = (i ? p.treads[i - 1].top : top) - deckT;
    const nose = tr.s1 + NOSING_M;
    // the riser under the tread above, then the tread (two boards on a full detail), its front
    // nosing over the riser below
    frameBox(buf, f, tr.s0 - 0.02, tr.s0, -hw + 0.04, hw - 0.04, tr.top - 0.002, riserTop, varied(PAINT.riser, 200 + i), k);
    if (light) {
      frameBox(buf, f, tr.s0 - 0.02, nose, -hw, hw, tr.top - deckT, tr.top, varied(PAINT.tread, 300 + i), k);
    } else {
      const mid = (tr.s0 - 0.02 + nose) / 2;
      frameBox(buf, f, tr.s0 - 0.02, mid - 0.003, -hw, hw, tr.top - deckT, tr.top, varied(PAINT.tread, 300 + i), k);
      frameBox(buf, f, mid + 0.003, nose, -hw, hw, tr.top - deckT, tr.top, varied(PAINT.tread, 400 + i), k);
    }
  }
  // the bottom riser, from the ground to the lowest tread
  {
    const lowTop = p.treads.length ? p.treads.at(-1).top : top;
    const sFoot = p.treads.length ? p.treads.at(-1).s1 : depth;
    frameBox(buf, f, sFoot - 0.02, sFoot, -hw + 0.04, hw - 0.04, below, lowTop - deckT, PAINT.riser, k);
  }
  if (p.rail) {
    const ps = 0.045; const hRail = 0.86; const r = 0.03;
    for (const side of [-1, 1]) {
      const w = side * (hw - ps);
      const lastTop = p.treads.at(-1)?.top ?? top;
      const sFoot = p.run - TREAD_M * 0.5;
      // newels at the landing's corner and at the foot of the flight, rails along both runs
      frameBox(buf, f, depth - 0.1 - ps, depth - 0.1 + ps, w - ps, w + ps, below, top + hRail + 0.06, PAINT.rail, k);
      frameBox(buf, f, sFoot - ps, sFoot + ps, w - ps, w + ps, footY - 0.05, lastTop + hRail + 0.08, PAINT.rail, k);
      frameSlope(buf, f, depth - 0.1, top + hRail, sFoot, lastTop + hRail, w - r, w + r, 0.05, PAINT.rail, k);
      frameSlope(buf, f, 0.02, top + hRail, depth - 0.1, top + hRail, w - r, w + r, 0.05, PAINT.rail, k);
      if (!light) {
        // balusters: square sticks a hand apart, from the deck or tread to the rail
        const bs = 0.016;
        for (let s = 0.14; s < depth - 0.16; s += 0.12) {
          frameBox(buf, f, s - bs, s + bs, w - bs, w + bs, top, top + hRail - 0.05, PAINT.rail, k);
        }
        for (const tr of p.treads) {
          const s = (tr.s0 + tr.s1) / 2;
          if (s > sFoot - 0.1) continue;
          const yRail = top + hRail + ((lastTop - top) * (s - (depth - 0.1))) / Math.max(0.01, sFoot - (depth - 0.1));
          frameBox(buf, f, s - bs, s + bs, w - bs, w + bs, tr.top, yRail - 0.04, PAINT.rail, k);
        }
      }
    }
  }
  return p;
}

