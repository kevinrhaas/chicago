/**
 * Every plant a season stands along the lots' crop rows: { kind, e, n, yaw, scale, variant,
 * conf, lot, bed, row }. A kind gardens.js cannot grow is reported, not drawn; a kind the season
 * does not keep (gardens.js SEASON_CROPS) is not planted. Exported for the test.
 */
export function cropPlan(lots, season = 'summer', { variants = 3, problems = null } = {}) {
  const out = [];
  for (const lot of lots ?? []) {
    for (const bed of lot.crops ?? []) {
      for (const [ri, row] of (bed.rows ?? []).entries()) {
        const [e0, n0, e1, n1, kind] = row;
        if (!CROP_KINDS[kind]) { problems?.push(`back yards: ${lot.parcel} plants an unknown crop "${kind}"`); continue; }
        const look = seasonLook(kind, season);
        if (!look) continue;
        const L = Math.hypot(e1 - e0, n1 - n0);
        const step = CROP_STEP_M[kind] ?? 0.8;
        const count = Math.max(1, Math.floor(L / step));
        const pad = (L - (count - 1) * step) / 2;
        const de = L > 0 ? (e1 - e0) / L : 1; const dn = L > 0 ? (n1 - n0) / L : 0;
        const along = Math.atan2(dn, de);
        const grade = bed.grade ?? lot.grade ?? 'reconstructed';
        for (let i = 0; i < count; i += 1) {
          const s = count === 1 ? L / 2 : pad + i * step;
          const j = strHash(`${lot.parcel}:${bed.bed}:${ri}:${i}`);
          const yaw = ROW_CROPS.has(kind) ? along + (j < 0.5 ? 0 : Math.PI) + (j - 0.5) * 0.05 : j * Math.PI * 2;
          out.push({ kind, e: e0 + de * s, n: n0 + dn * s, yaw, scale: (0.9 + 0.2 * hash(i + 1, Math.round(j * 1e6))) * (look.size ?? 1),
            variant: Math.floor(j * 1e3) % variants, conf: CONF[grade] ?? 1, grade, lot, bed, row: ri });
        }
      }
    }
  }
  return out;
}

