function area2(poly) {
  let s = 0;
  for (let i = 0; i < poly.length; i += 1) {
    const [x0, y0] = poly[i]; const [x1, y1] = poly[(i + 1) % poly.length];
    s += x0 * y1 - x1 * y0;
  }
  return s;
}
export function pointInPolygon(e, n, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i, i += 1) {
    const [xi, yi] = poly[i]; const [xj, yj] = poly[j];
    if ((yi > n) !== (yj > n) && e < ((xj - xi) * (n - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
/** The part of a convex polygon where `side(p) >= 0` (Sutherland-Hodgman, one plane). */
function clipBy(poly, side) {
  const out = [];
  for (let i = 0; i < poly.length; i += 1) {
    const a = poly[i]; const b = poly[(i + 1) % poly.length];
    const sa = side(a); const sb = side(b);
    if (sa >= 0) out.push(a);
    if ((sa >= 0) !== (sb >= 0)) {
      const t = sa / (sa - sb);
      out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
    }
  }
  return out;
}

/**
 * A simple plan polygon (either winding, concave allowed) as counter-clockwise plan
 * triangles cut on the terrain lattice: ear-clipped first, then each triangle clipped to
 * every lattice cell it meets, each cell's piece (convex) in a fan. So every triangle lies
 * inside one cell, where the bilinear ground is nearest a plane, and every vertex on a cell
 * line is shared by the pieces either side of it: no crack, no bridge.
 */
export function drapeTriangles(poly, grid) {
  if (!Array.isArray(poly) || poly.length < 3) return [];
  let pts = poly.map((p) => [Number(p[0]), Number(p[1])]);
  if (pts.length > 3 && Math.hypot(pts[0][0] - pts.at(-1)[0], pts[0][1] - pts.at(-1)[1]) < 1e-9) pts = pts.slice(0, -1);
  if (!pts.every((p) => Number.isFinite(p[0]) && Number.isFinite(p[1]))) return [];
  if (area2(pts) < 0) pts = [...pts].reverse();
  const tris = THREE.ShapeUtils.triangulateShape(pts.map(([x, y]) => new THREE.Vector2(x, y)), []);
  const cell = grid?.cellM > 0 ? grid.cellM : FALLBACK_CELL_M;
  const oE = grid?.originE ?? 0; const oN = grid?.originN ?? 0;
  const out = [];
  for (const [a, b, c] of tris) {
    const tri = [pts[a], pts[b], pts[c]];
    if (area2(tri) < 0) tri.reverse();
    const es = tri.map((p) => p[0]); const ns = tri.map((p) => p[1]);
    const i0 = Math.floor((Math.min(...es) - oE) / cell); const i1 = Math.ceil((Math.max(...es) - oE) / cell);
    const j0 = Math.floor((Math.min(...ns) - oN) / cell); const j1 = Math.ceil((Math.max(...ns) - oN) / cell);
    for (let i = i0; i < i1; i += 1) {
      const eLo = oE + i * cell; const eHi = eLo + cell;
      let strip = clipBy(tri, (p) => p[0] - eLo);
      strip = clipBy(strip, (p) => eHi - p[0]);
      if (strip.length < 3) continue;
      for (let j = j0; j < j1; j += 1) {
        const nLo = oN + j * cell; const nHi = nLo + cell;
        let piece = clipBy(strip, (p) => p[1] - nLo);
        piece = clipBy(piece, (p) => nHi - p[1]);
        // a vertex on a cell line comes back twice from the clip: drop the repeat
        piece = piece.filter((p, k) => {
          const q = piece[(k + piece.length - 1) % piece.length];
          return Math.abs(p[0] - q[0]) > 1e-9 || Math.abs(p[1] - q[1]) > 1e-9;
        });
        if (piece.length < 3 || Math.abs(area2(piece)) < 1e-8) continue;
        for (let k = 1; k + 1 < piece.length; k += 1) {
          const t = [piece[0], piece[k], piece[k + 1]];
          if (area2(t) > 1e-10) out.push(t);
        }
      }
    }
  }
  return out;
}

/** World metres to a texture's (u, v): u along the compass bearing `alongDeg`, v across it. */
export function uvAt(e, n, alongDeg, tileU, tileV) {
  const th = (Number(alongDeg) || 0) * Math.PI / 180;
  const ax = Math.sin(th); const ay = Math.cos(th);
  return [(e * ax + n * ay) / tileU, (e * ay - n * ax) / tileV];
}

