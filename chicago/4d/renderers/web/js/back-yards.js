/**
 * back-yards.js — the 1904 district's back and side yards: the paved terraces by the rear
 * doors, the walks out to the coach houses and round to the front steps, the gangways, the
 * drying yards and the kitchen gardens (T-3488).
 *
 * WHY. The owner, 2026-11-07, of the Prairie Avenue lots behind the houses: *"patios and
 * entertaining space near the rear doors and walkways to the carriage houses and to the front
 * steps and maybe in gangways etc ... with correct textured surfaces"*, and gardens. Behind
 * the houses the lots were the bare sward of the terrain from the back wall to the alley.
 *
 * WHAT IT DRAWS, from `data/back_yards/<scene>.json` (generated by
 * tools/lay_prairie_1904_back_yards.py from the street grid's lots and the houses' own
 * placements; its `_doc` is the contract):
 *
 *   surfaces  every paved or worn piece of the yard, as a textured ground decal lying on the
 *             terrain: each polygon is cut on the heightfield's own lattice (terrain.grid), so
 *             no triangle bridges a cell and floats or sinks, and wears the PBR maps of the
 *             library `assets/textures/prairie_1904_pbr/` its material names (colour, normal,
 *             packed ORM), laid in world metres at the material's tile and turned to its
 *             `along_deg`, so two pieces of one paving meet without a seam. One merged mesh
 *             per material, per stacking order, per CHUNK_M square of the district;
 *   doors     a back door's leaf where the house's model carries none (a painted panelled door,
 *             glazed above, in its casing, on a stone sill), and its stoop: a landing at the
 *             sill and straight steps down to the ground at about RISE_M a riser and TREAD_M a
 *             tread, in painted porch boards on stringers over a skirt, or in stone, with a
 *             handrail where the rise passes RAIL_RISE_M. All in one vertex-coloured mesh per
 *             chunk with the posts;
 *   posts     the clothes posts of a drying yard, a square post with its cross arm, and the
 *             lines from arm to arm (one line draw for the district);
 *   crops     a kitchen garden's rows, grown by gardens.js's own growers (its templates, its
 *             leaf atlas and its SEASON_CROPS) in two batches for the district.
 * The yard's shrubs, trees, creeper and beds are front-yards.js's, in that file's row formats:
 * main.js hands it this file's lots (`extraLots`), so they grow, take the Season, pick and
 * thin by detail exactly as the front yards' do.
 *
 * HOW A DECAL LIES (memory: the ground-decal depth and paving depth levels notes). Every
 * surface writes no depth and carries a small polygon offset with no slope term (T-1805), and
 * is drawn at BACK_YARD_RENDER_ORDER plus its `order` among a lot's overlapping pieces: after
 * every opaque surface that holds the depth buffer over it (the terrain, the water plane at
 * order 1, a wall, a stoop, a shrub), and before the roadways at ROAD_RENDER_ORDER (10), which
 * nothing here may paint over. `tools/test_back_yards.mjs` holds both.
 *
 * WHAT IS EVIDENCE. Each lot names its scheme and its grade; every surface, door and post
 * carries its own `grade`, so the confidence view shows which is which, and a click on any of
 * them names the lot, the kind, the material, the grade, the note and the liberty
 * (docs/LIBERTIES.md, the file's `liberty`).
 *
 * THE SEASON (T-3399's rule: nothing stays July-green out of season). The paving, the earth
 * and the stoops take season.js's snow by how much of it each keeps (SEASON_KIND); a crop
 * row stands only in the seasons gardens.js's SEASON_CROPS keeps it, as that season's look.
 *
 * WHAT IT COSTS. One merged mesh per material and chunk, plus one fixtures mesh per chunk,
 * one line draw and two crop batches: a handful of draws in any view. A phone binds each
 * paving's colour and normal maps but not its ORM, draws the stoops as solid blocks (no boards,
 * no balusters), casts no shadow from them, draws nothing past VIEW_M.light, and grows the
 * crops only once they come into view. A layer that misses its maps degrades to flat tones
 * and a recorded problem, never to a throw.
 *
 * A scene that does not list `back_yards` hands this no data base and it draws nothing; a
 * failed fetch draws nothing and records a problem.
 */

