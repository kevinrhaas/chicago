/**
 * The registration for one year: `toToday(e, n)` carries a scene point to today's ground,
 * `toScene(e, n)` carries a point of today's map (a City centreline) onto the scene's.
 * A year with no controls is the identity.
 */
export function createRegistration(sceneId, table = CONTROLS) {
  const year = String(sceneId ?? '');
  const rows = table.filter((r) => String(r[1]).split(' ').includes(year));
  const n = rows.length;
  const se = new Float64Array(n), sn = new Float64Array(n), de = new Float64Array(n), dn = new Float64Array(n);
  rows.forEach((r, i) => { se[i] = r[2]; sn[i] = r[3]; de[i] = r[4] - r[2]; dn[i] = r[5] - r[3]; });
  const s2 = SOFT_M * SOFT_M;
  /** The shift [dE, dN] at a scene point. */
  function shift(e, nn) {
    if (!n) return [0, 0];
    let w = 0, x = 0, y = 0;
    for (let i = 0; i < n; i++) {
      const dx = e - se[i], dy = nn - sn[i];
      const k = (dx * dx + dy * dy + s2) ** -POWER;
      w += k; x += k * de[i]; y += k * dn[i];
    }
    return [x / w, y / w];
  }
  function toToday(e, nn) {
    const [x, y] = shift(e, nn);
    return [e + x, nn + y];
  }
  function toScene(e, nn) {
    // The shift is smooth and much smaller than the distance it turns over, so the
    // fixed point p = q - shift(p) converges in a few steps.
    let pe = e, pn = nn;
    for (let i = 0; i < 8; i++) {
      const [x, y] = shift(pe, pn);
      const qe = e - x, qn = nn - y;
      if (Math.abs(qe - pe) < 0.01 && Math.abs(qn - pn) < 0.01) return [qe, qn];
      pe = qe; pn = qn;
    }
    return [pe, pn];
  }
  return { year, count: n, shift, toToday, toScene };
}
