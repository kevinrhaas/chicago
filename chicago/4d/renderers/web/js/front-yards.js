/**
 * @param {object} o dataBase (data/ root, or null when the scene does not list the layer) ·
 *   sceneId · terrain · confidence · problems · detail · lowSpec · mode (the Season's tree
 *   mode) · levelAt (the street grid's drop below the field at a point) · grownMaterials (the
 *   parkway elms' materials, so the leaf and bark atlases are loaded once) · checkpoint
 */
export async function createFrontYards({
  dataBase, sceneId, terrain, confidence = null, problems = [], detail = 'full', levelAt = null,
  lowSpec = false, mode = 'summer', grownMaterials = null, checkpoint = () => null,
} = {}) {
  const group = new THREE.Group();
  group.name = 'front-yards';
  const stats = { lots: 0, shrubs: 0, trees: 0, beds: 0, bedPlants: 0, creeper: 0, plants: 0,
    triangles: 0, drawCalls: 0, detail, mode };
  const out = {
    group, stats, records: [],
    pickAt: () => null, update() {}, setDetail: async () => {}, setSeason: async () => {}, settle() {},
    cardFor: () => null, dispose() {},
  };
  if (!dataBase || !terrain) return out;
  let doc;
  try {
    doc = await getJSON(new URL(`front_yards/${sceneId}.json`, dataBase));
  } catch (err) {
    problems.push(`front yards: ${err.message} — no front-yard planting is drawn`);
    return out;
  }
  const lots = doc.lots ?? [];
  out.records = lots;
  stats.lots = lots.length;
  if (!lots.length) return out;
  const groundAt = (e, n) => terrain.surfaceHeight(e, n) + (levelAt?.(e, n) ?? 0);
  const disposers = [];

  /* ---- the beds' loam: one mesh, a low crowned mound with its cut edge ---- */
  const beds = [];
  {
    const pos = []; const conf = [];
    for (const lot of lots) {
      for (const [i, b] of (lot.beds ?? []).entries()) {
        const [e, n, a, w, heading, kind, palette] = b;
        const h = (heading * Math.PI) / 180;
        const ax = [Math.sin(h), Math.cos(h)]; const ay = [Math.cos(h), -Math.sin(h)];
        const SEG = kind === 'border' ? 4 : 24;
        const ring = (k) => {
          if (kind === 'border') {
            const t = [[-1, -1], [1, -1], [1, 1], [-1, 1]][k]; return [t[0] * a, t[1] * w];
          }
          const t = (k / SEG) * Math.PI * 2; return [Math.cos(t) * a, Math.sin(t) * w];
        };
        const at = (u, v) => [e + ax[0] * u + ay[0] * v, n + ax[1] * u + ay[1] * v];
        const y0 = groundAt(e, n);
        const top = y0 + BED_LIFT_M;
        for (let k = 0; k < SEG; k += 1) {
          const [pu, pv] = ring(k); const [qu, qv] = ring((k + 1) % SEG);
          const p = at(pu, pv); const q = at(qu, qv);
          const pi = at(pu * 0.85, pv * 0.85); const qi = at(qu * 0.85, qv * 0.85);
          const crown = top + 0.04;
          // the crowned middle, the shoulder, and the cut edge down to the lawn
          pos.push(e, crown, -n, qi[0], top + 0.02, -qi[1], pi[0], top + 0.02, -pi[1]);
          pos.push(pi[0], top + 0.02, -pi[1], qi[0], top + 0.02, -qi[1], q[0], top, -q[1]);
          pos.push(pi[0], top + 0.02, -pi[1], q[0], top, -q[1], p[0], top, -p[1]);
          pos.push(p[0], top, -p[1], q[0], top, -q[1], q[0], y0 - 0.02, -q[1]);
          pos.push(p[0], top, -p[1], q[0], y0 - 0.02, -q[1], p[0], y0 - 0.02, -p[1]);
          for (let z = 0; z < 15; z += 1) conf.push(CONF.reconstructed);
        }
        beds.push({ lot, i, e, n, a, w, ax, ay, kind, palette, y: top, grade: 'reconstructed' });
      }
    }
    if (pos.length) {
      const geo = new THREE.BufferGeometry();
      geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
      geo.setAttribute('_confidence', new THREE.Float32BufferAttribute(conf, 1));
      geo.computeVertexNormals();
      const mat = new THREE.MeshStandardMaterial({ color: LOAM, roughness: 1, metalness: 0, side: THREE.DoubleSide });
      mat.name = 'front-yards-loam';
      confidence?.patch(mat);
      patchSeason(mat, 0.6);
      const mesh = new THREE.Mesh(geo, mat);
      mesh.name = 'front-yards-beds';
      mesh.receiveShadow = true;
      group.add(mesh);
      disposers.push(() => { geo.dispose(); mat.dispose(); });
    }
  }
  stats.beds = beds.length;

  /* ---- what grows: every plant one stem in the grown batches ------------- */
  const placed = [];   // { x, z, y, h, r, plant, conf, grade, lot, kind, index, yaw, scale }
  const tubs = [];     // { x, z, y, h, r, conf, box }
  for (const lot of lots) {
    // A row is [east, north, plant, height, crown width, (grade), (stand, tub)]: the planter
    // measured the width against the doors and walks, so the plant is drawn to it. A tub
    // plant's row adds what its tub stands on above the ground and the tub's own height.
    for (const kind of ['shrub', 'tree']) {
      for (const [i, r] of (lot[`${kind}s`] ?? []).entries()) {
        const [e, n, plant, h, w, grade, standM = 0, tubM = 0, vessel = 'tub'] = r;
        const g = grade ?? lot.grade;
        const y0 = groundAt(e, n) + standM;
        if (tubM > 0 && vessel !== 'over') {
          tubs.push({ x: e, z: -n, y: y0, h: tubM, r: Math.min(0.42, Math.max(0.26, w * 0.28)), conf: CONF[g] ?? 1,
            box: vessel === 'box' });
        }
        placed.push({ x: e, z: -n, y: y0 + tubM, h, w, plant, grade: g, conf: CONF[g] ?? 1, lot, kind, index: i,
          tub: tubM > 0, vessel });
      }
    }
    const cg = lot.pictured_notes?.creeper?.grade ?? 'reconstructed';
    for (const [i, c] of (lot.creeper ?? []).entries()) {
      const [e, n, facing, w, h, form] = c;
      placed.push({ x: e, z: -n, y: groundAt(e, n), h, w, facing, plant: 'ivy', grade: cg, conf: CONF[cg] ?? 1,
        lot, kind: 'creeper', index: i, mantle: form === 'mantle' || form === 'mantle_sill' ? form : null });
      stats.creeper += 1;
    }
  }
  for (const b of beds) {
    for (const p of bedPlanting(b)) {
      const e = b.e + b.ax[0] * p.u + b.ay[0] * p.v; const n = b.n + b.ax[1] * p.u + b.ay[1] * p.v;
      const spec = YARD_PLANTS[p.plant];
      const j = hash(Math.round(e * 53), Math.round(n * 59));
      placed.push({ x: e, z: -n, y: b.y - 0.01, h: (spec.h[0] + (spec.h[1] - spec.h[0]) * j) * p.s,
        plant: p.plant, grade: 'reconstructed', conf: CONF.reconstructed, lot: b.lot, kind: 'bedding', bed: b });
      stats.bedPlants += 1;
    }
  }
  stats.shrubs = placed.filter((p) => p.kind === 'shrub').length;
  stats.trees = placed.filter((p) => p.kind === 'tree').length;
  stats.plants = placed.length;

  /* ---- the tubs: one mesh, each a staved tub a little wider at its rim ---- */
  // Tub plants were wintered under glass and set out for the summer, so the winter
  // Season draws neither the tubs nor what grows in them.
  let tubMesh = null;
  stats.tubs = tubs.length;
  if (tubs.length) {
    const pos = []; const conf = []; const col = [];
    const paint = new THREE.Color(TUB_PAINT); const post = new THREE.Color(BOX_POST_PAINT);
    // A box: its four panels between the posts and the soil in it, and a post at each corner.
    const cuboid = (x0, x1, y0, y1, z0, z1, c, k) => {
      const q = (a, b, cc, d) => {
        pos.push(...a, ...b, ...cc, ...a, ...cc, ...d);
        for (let i = 0; i < 6; i += 1) { conf.push(k); col.push(c.r, c.g, c.b); }
      };
      q([x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]);
      q([x1, y0, z0], [x0, y0, z0], [x0, y1, z0], [x1, y1, z0]);
      q([x1, y0, z1], [x1, y0, z0], [x1, y1, z0], [x1, y1, z1]);
      q([x0, y0, z0], [x0, y0, z1], [x0, y1, z1], [x0, y1, z0]);
      q([x0, y1, z1], [x1, y1, z1], [x1, y1, z0], [x0, y1, z0]);
    };
    for (const t of tubs) {
      if (t.box) {
        const a = BOX_HALF_M; const p = 0.045; const top = t.y + t.h;
        cuboid(t.x - a + p, t.x + a - p, t.y + BOX_LEGS_M, top - 0.03, t.z - a + p, t.z + a - p, paint, t.conf);
        for (const [sx, sz] of [[-1, -1], [1, -1], [1, 1], [-1, 1]]) {
          const cx = t.x + sx * (a - p); const cz = t.z + sz * (a - p);
          cuboid(cx - p, cx + p, t.y - 0.02, top, cz - p, cz + p, post, t.conf);
        }
        continue;
      }
      const rb = t.r * 0.86; const top = t.y + t.h;
      for (let k = 0; k < TUB_SEG; k += 1) {
        const a0 = (k / TUB_SEG) * Math.PI * 2; const a1 = ((k + 1) / TUB_SEG) * Math.PI * 2;
        const [c0, s0, c1, s1] = [Math.cos(a0), Math.sin(a0), Math.cos(a1), Math.sin(a1)];
        // the side, from a footing just under the floor to the rim, and the soil's top
        pos.push(t.x + c0 * rb, t.y - 0.02, t.z + s0 * rb, t.x + c1 * t.r, top, t.z + s1 * t.r, t.x + c1 * rb, t.y - 0.02, t.z + s1 * rb);
        pos.push(t.x + c0 * rb, t.y - 0.02, t.z + s0 * rb, t.x + c0 * t.r, top, t.z + s0 * t.r, t.x + c1 * t.r, top, t.z + s1 * t.r);
        pos.push(t.x, top - 0.04, t.z, t.x + c1 * t.r * 0.94, top - 0.04, t.z + s1 * t.r * 0.94, t.x + c0 * t.r * 0.94, top - 0.04, t.z + s0 * t.r * 0.94);
        for (let z = 0; z < 9; z += 1) { conf.push(t.conf); col.push(paint.r, paint.g, paint.b); }
      }
    }
    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    geo.setAttribute('color', new THREE.Float32BufferAttribute(col, 3));
    geo.setAttribute('_confidence', new THREE.Float32BufferAttribute(conf, 1));
    geo.computeVertexNormals();
    const mat = new THREE.MeshStandardMaterial({ color: 0xffffff, vertexColors: true, roughness: 0.8, metalness: 0,
      side: THREE.DoubleSide });
    mat.name = 'front-yards-tubs';
    confidence?.patch(mat);
    const mesh = new THREE.Mesh(geo, mat);
    mesh.name = 'front-yards-tubs';
    tubMesh = mesh;
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    group.add(mesh);
    disposers.push(() => { geo.dispose(); mat.dispose(); });
  }

  /* ---- the materials: the parkway elms' own, else grown here ------------- */
  const uWind = { value: 0 };
  let mats = grownMaterials;
  let ownMats = false;
  if (!mats) {
    mats = await createGrownTreeMaterials({
      assetBase: resolveBases().assetBase, uWind, confidence, patchWind: patchTreeWind,
      lowSpec: lowSpec || detail === 'light', alphaCutoff: TREE_ALPHA_CUTOFF, problems, fade: true,
    });
    ownMats = true;
  }
  const ivySpec = (w, h, conf) => ({ speciesId: 'parthenocissus_tricuspidata', common: 'Boston ivy',
    form: 'vine_wall', leaf: 'maple', h: [h, h], crownW: [w, w], dark: 0x29421f, light: 0x648a3a,
    bark: 0x6b5a48, conf, sinkM: 0 });

  let forest = null;
  let current = { mode: null, detail: null };
  const build = async (wantMode, wantDetail) => {
    if (forest) { group.remove(forest.group); forest.dispose(); forest = null; }
    current = { mode: wantMode, detail: wantDetail };
    stats.mode = wantMode; stats.detail = wantDetail;
    const lvl = YARD_LEVELS[wantDetail] ? wantDetail : 'full';
    const grown = new TreeInstances({ level: lvl, shadowM: SHADOW_M[lvl], name: 'front-yards',
      levels: YARD_LEVELS, cull: true, fadeS: FADE_S });
    if (tubMesh) tubMesh.visible = wantMode !== 'winter';
    for (const p of placed) {
      if (p.tub && wantMode === 'winter') continue;
      if (p.kind === 'creeper') {
        // Its +x out of the wall: a compass bearing turned into the batches' yaw.
        // a pictured stretch wholly clothed keeps its own level-topped variants, and the low
        // patches under its windows theirs, so neither is grown at the other's height (T-1881)
        const spec = { ...ivySpec(2.4, 6, p.conf), ...(p.mantle ? { arch: p.mantle } : {}) };
        grown.add({ ...spec, h: [p.h, p.h] }, p.x, p.y, p.z, 1,
          { yaw: Math.PI / 2 - (p.facing * Math.PI) / 180, crownW: p.w });
        continue;
      }
      const spec = specOf(p.plant, p.conf);
      const own = spec.own && p.w ? { crownW: [p.w, p.w], own: `${p.h}x${p.w}` } : {};
      grown.add({ ...spec, h: [p.h, p.h], ...own }, p.x, p.y, p.z, 1, { crownW: p.w ?? null });
    }
    const pause = checkpoint(); if (pause) await pause;
    forest = await grown.build({ ...mats, checkpoint, season: SEASON[wantMode] ?? {} });
    group.add(forest.group);
    stats.drawCalls = forest.stats.drawCalls + (beds.length ? 1 : 0);
    stats.grown = forest.stats;
  };
  await build(SEASON[mode] ? mode : 'summer', detail);

  let wind = 0;
  out.update = (dt, camera = null) => {
    if (ownMats) { wind += dt || 0; uWind.value = wind; }
    if (camera && forest) {
      forest.update(camera.position, dt || 0);
      stats.triangles = forest.stats.triangles;
    }
  };
  out.setDetail = async (d) => {
    if (!YARD_LEVELS[d] || d === current.detail) return;
    await build(current.mode, d);
  };
  out.setSeason = async (m) => {
    const want = SEASON[m] ? m : 'summer';
    if (want === current.mode) return;
    await build(want, current.detail);
  };
  /** Deal now, from this eye (a still frame for a reading or a shot). */
  out.settle = (camera) => {
    if (camera && forest) forest.update(camera.position, 0);
    forest?.settle();
    if (forest) stats.triangles = forest.stats.triangles;
  };

  /* ---- picks: a shrub, a tree, an ivy patch or a bed under the crosshair -- */
  const ray = new THREE.Raycaster();
  const PICK_M = 45;
  out.pickAt = (ndc, camera) => {
    if (!camera || !group.visible) return null;
    ray.setFromCamera(ndc ?? new THREE.Vector2(0, 0), camera);
    const o = ray.ray.origin; const d = ray.ray.direction;
    let best = null;
    const sphere = new THREE.Sphere(); const hitP = new THREE.Vector3();
    for (const p of placed) {
      if (p.kind === 'bedding' || (p.tub && current.mode === 'winter') || Math.hypot(p.x - o.x, p.z - o.z) > PICK_M) continue;
      const r = p.kind === 'creeper' ? Math.min(p.w ?? 1.5, p.h) * 0.5
        : p.kind === 'tree' ? p.h * 0.3 : Math.max(0.4, p.h * 0.5);
      sphere.center.set(p.x, p.y + (p.kind === 'tree' ? p.h * 0.62 : p.h * 0.5), p.z);
      sphere.radius = r;
      if (!ray.ray.intersectSphere(sphere, hitP)) continue;
      const t = hitP.distanceTo(o);
      if (!best || t < best.distance) best = { hit: p, distance: t, point: hitP.clone() };
    }
    for (const b of beds) {
      if (Math.hypot(b.e - o.x, -b.n - o.z) > PICK_M || Math.abs(d.y) < 1e-6) continue;
      const t = (b.y + 0.2 - o.y) / d.y;
      if (!(t > 0)) continue;
      const x = o.x + d.x * t - b.e; const zN = -(o.z + d.z * t) - b.n;
      const u = x * b.ax[0] + zN * b.ax[1]; const v = x * b.ay[0] + zN * b.ay[1];
      const inside = b.kind === 'border' ? Math.abs(u) <= b.a && Math.abs(v) <= b.w
        : (u * u) / (b.a * b.a) + (v * v) / (b.w * b.w) <= 1;
      if (inside && (!best || t < best.distance)) {
        best = { hit: { lot: b.lot, kind: 'bed', index: b.i, bedKind: b.kind, grade: b.grade },
          distance: t, point: new THREE.Vector3(o.x + d.x * t, b.y, o.z + d.z * t) };
      }
    }
    if (!best) return null;
    const record = plantCard(best.hit, doc);
    return { id: record.id, record, point: best.point, distance: best.distance };
  };
  out.cardFor = (id) => {
    const m = /^front-yard\.(.+)\.(shrub|tree|bed|creeper)\.(\d+)$/.exec(id ?? '');
    if (!m) return null;
    const lot = lots.find((l) => l.parcel === m[1]);
    if (!lot) return null;
    const i = Number(m[3]);
    const list = { shrub: lot.shrubs, tree: lot.trees, bed: lot.beds, creeper: lot.creeper }[m[2]] ?? [];
    const r = list[i];
    if (!r) return null;
    const hit = m[2] === 'bed' ? { lot, kind: 'bed', index: i, bedKind: r[5], grade: lot.grade }
      : m[2] === 'creeper' ? { lot, kind: 'creeper', index: i, grade: lot.pictured_notes?.creeper?.grade ?? lot.grade }
        : { lot, kind: m[2], index: i, plant: r[2], grade: r[5] ?? lot.grade, tub: (r[7] ?? 0) > 0, vessel: r[8] ?? 'tub' };
    return plantCard(hit, doc);
  };
  out.dispose = () => {
    if (forest) { group.remove(forest.group); forest.dispose(); }
    if (ownMats) mats.dispose();
    for (const f of disposers) f();
  };
  return out;
}
