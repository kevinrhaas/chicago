/**
 * front-yards.js — the 1904 district's front yards: garden shrubs, yard trees, bedding, ivy
 * (T-3203, rebuilt T-3223).
 *
 * WHY. The owner, 2026-10-27: *"plants in front of the houses they seem to be missing flora
 * on the property"*. T-3203 drew them as lumps of faceted leaf; the owner, 2026-10-28: *"I
 * find the bushes and plants and flowers added to be very low quality ... make sure they
 * don't block doorways"*. So every plant here is GROWN, on the same path as the parkway elms
 * and the timber (tree-model.js, tree-instances.js): a clump of stems from the ground, its
 * branches, and its leaf carried in sprays off the leaf atlas, at three levels by distance,
 * casting the sun's shadow and moving in the wind with the elms over it.
 *
 * WHAT IT DRAWS, from `data/front_yards/<scene>.json` (generated by
 * tools/plant_prairie_1904_front_yards.py from the street grid's lots and the houses' own
 * baked models, kept clear of every stoop, step, walk, gate and door's way, which its
 * --check holds). The lawn is the ground's own sward.
 *
 *   shrubs    the nursery shrubs of an 1890s yard (YARD_PLANTS): lilac, Van Houtte's
 *             spiraea, the smooth hydrangea in its July flower, the garden rose in bloom,
 *             arborvitae sheared to a cone or a ball, or clipped to a column (Pullman's terrace);
 *   trees     a young maple or linden in the lawn, as the 1816 and Pullman photographs show;
 *   beds      a round or oval bed cut in the lawn, bedded out as the period's books lay them:
 *             scarlet or pink geraniums massed, or edged with coleus;
 *   creeper   Boston ivy held flat up the walls a picture shows it on (Pullman's, 1912's);
 *   tubs      Pullman's summer tub plants (T-1934): a clipped standard, cone or column, or a
 *             palm out of the palm house, in a painted tub, at grade or up on the palm house's
 *             terrace, where the 1894 plate and Taylor's 16555 stand them. Their rows carry two more numbers, what the tub stands on above the
 *             ground (the terrace floor, read off the baked model) and the tub's height, and may
 *             name the vessel (T-1881): 'box', a square planting box on legs (the boxed
 *             standards before the 1800 Calumet conservatory, Lowe's c. 1897 print), or 'over',
 *             a plant grown over the box of the row at its own spot, its foot the height given.
 *
 * WHAT IS EVIDENCE. Pullman's ivy and its shrub border along 18th Street are in the Detroit
 * Publishing views and are attested; 1912's ivy is in a later photograph, so inferred; the
 * rest is reconstructed (docs/LIBERTIES.md L-prairie-front-yards-3203). Each plant carries its
 * tier, so the confidence view shows which is which, and a click on one says so in words.
 *
 * A scene that does not list `front_yards` hands this no data base and it draws nothing; a
 * failed fetch draws nothing and records a problem.
 */

