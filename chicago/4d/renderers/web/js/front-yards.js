async function getJSON(url) {
  const res = await fetch(url, { cache: 'no-cache' });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} — ${url}`);
  return res.json();
}

/** A small deterministic hash, so a re-load grows the same yard. */
function hash(a, b = 0) {
  let h = Math.imul((a * 73856093) ^ (b * 19349663), 0x27d4eb2d) >>> 0;
  h ^= h >>> 15; h = Math.imul(h, 0x2c1b3c6d) >>> 0; h ^= h >>> 12;
  return (h >>> 0) / 4294967296;
}

/** The yard plant's spec for the batches, its tier written in. */
function specOf(key, conf) {
  const p = YARD_PLANTS[key] ?? YARD_PLANTS.spiraea;
  return { arch: p.speciesId, ...p, form: 'yard_shrub', conf };
}

