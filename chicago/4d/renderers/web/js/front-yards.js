/** The plants a bed is bedded out with: its centre clump, its mass on a staggered
 *  grid, and its edge in a ring; positions in the bed's (u along, v across) frame. */
function bedPlanting(b) {
  const scheme = BEDDING[b.palette % BEDDING.length];
  const out = [];
  const strip = b.kind === 'border';
  const inside = (u, v, k) => (strip ? Math.abs(u) <= b.a - k && Math.abs(v) <= b.w - k
    : (u * u) / ((b.a - k) ** 2) + (v * v) / ((b.w - k) ** 2) <= 1);
  const edge = scheme.edge && !strip ? 0.28 : 0;
  if (edge) {
    const per = Math.PI * (3 * (b.a + b.w) - Math.sqrt((3 * b.a + b.w) * (b.a + 3 * b.w)));
    const n = Math.max(6, Math.round(per / 0.4));
    for (let i = 0; i < n; i++) {
      const t = (i / n) * Math.PI * 2;
      out.push({ plant: scheme.edge, u: Math.cos(t) * (b.a - 0.2), v: Math.sin(t) * (b.w - 0.2), s: 0.85 });
    }
  }
  const centre = scheme.centre && !strip && Math.min(b.a, b.w) >= 0.75;
  if (centre) {
    const k = Math.min(b.a, b.w) >= 1.05 ? 3 : 1;
    for (let i = 0; i < k; i++) {
      const t = (i / k) * Math.PI * 2 + 0.4;
      out.push({ plant: scheme.centre, u: k > 1 ? Math.cos(t) * 0.28 : 0, v: k > 1 ? Math.sin(t) * 0.28 : 0, s: 1 });
    }
  }
  const step = 0.68;
  let row = 0;
  for (let v = -b.w; v <= b.w; v += step * 0.87, row++) {
    for (let u = -b.a + (row % 2 ? step / 2 : 0); u <= b.a; u += step) {
      if (!inside(u, v, edge ? 0.42 : 0.18)) continue;
      if (centre && Math.hypot(u, v) < 0.55) continue;
      const j = hash(Math.round((b.e + u) * 41), Math.round((b.n + v) * 37));
      out.push({ plant: scheme.mass, u: u + (j - 0.5) * 0.1, v: v + (hash(j * 1e6, 3) - 0.5) * 0.1, s: 0.9 + 0.2 * j });
    }
  }
  return out;
}

