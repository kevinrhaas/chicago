#!/usr/bin/env python3
"""Lay the 1871 city's street furniture: gas lamps, telegraph poles and wires, and hitching
posts along the shop walks (the owner, 2026-11-21).

    python3 tools/lay_1871_street_furniture.py           # write data/street_furniture/1871.json
    python3 tools/lay_1871_street_furniture.py --check   # the committed file is what this writes

The owner, 2026-11-21: "I think we need trees and other streetscape, analyze street scenes
from the era and add the correct supporting street furniture and other appropriate items
around the businesses and houses and on the streets".

WHAT THE PICTURES SHOW. The stereographs of the downtown streets the scene already cites,
read for what stands on the walks rather than for the buildings they were solved on:

  * Carbutt's No. 55 (LOC 1s47905), Lake and Dearborn: a cast-iron gas lamp post at the
    corner, on the walk at the kerb, beside a tall wooden pole with short crossarms; barrels
    on the far corner's walk; awnings down Lake Street.
  * Carbutt's No. 52 (LOC 1s12371), Clark and Randolph: a gas lamp at the corner of the
    square, telegraph poles of five or six crossarms on the kerb of Clark Street with their
    wires down the street, a stand of closed hacks at the square's kerb.
  * Carbutt's No. 139 (LOC 1s47902), Washington Street: a pair of lamp posts at the opera
    house's door, a horse and buggy standing at the kerb.

So: a lamp at the corners, the lamps of the business streets between corners, the telegraph
lines down the principal business streets on poles at the kerb, and posts to tie a horse to
along the shop walks, where every picture has a horse standing.

WHAT IT READS. data/context/1871.json (generated by generators/city_1871_emit.py): its walk
surfaces (each raised plank walk's centreline, width and height), its named junctions, its
core polygon, and its buildings (which walks front attached shop rows, and in which district).
The source records the kinds cite are copied in from data/sources/, so a card can show them.

GRADES. The kinds' forms are inferred from the pictures (the lamp post is the 1904 layer's
cast-iron post, the same pattern of post and lantern the 1860s pictures show at the corners);
the hitching post's form is reconstructed. Every item's place is reconstructed: the pictures
show that such things stood at such places, not where each one stood. docs/LIBERTIES.md
L-1871-streetscape is the record. Deterministic: no randomness but a fixed per-walk phase.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTEXT = ROOT / "data" / "context" / "1871.json"
LAMPS_1904 = ROOT / "data" / "street_furniture" / "1904.json"
SOURCES = ROOT / "data" / "sources"
OUT = ROOT / "data" / "street_furniture" / "1871.json"
TREES_OUT = ROOT / "data" / "street_trees" / "1871.json"
LIBERTY = "L-1871-streetscape"
TICKET = "T-3686"

PICTURES = ["loc_stereo_1s47905_tremont_house", "loc_stereo_1s12371_sherman_house",
            "loc_stereo_1s47902_crosbys_opera_house"]
# The principal business streets that carried the telegraph lines (the Clark Street poles of
# Carbutt's No. 52 and the Lake Street pole of No. 55): drawn on these, one side each.
TELEGRAPH_STREETS = ("Lake Street", "Clark Street", "State Street", "Randolph Street", "Madison Street",
                     "Washington Street", "LaSalle Street", "Dearborn Street", "South Water Street",
                     "Wells Street", "Wabash Avenue", "Canal Street", "Halsted Street", "Kinzie Street",
                     "North Clark Street", "West Madison Street", "West Randolph Street", "West Lake Street")

LAMP_KERB_INSET_M = 0.45      # a lamp's centre in from the kerb edge of the walk
LAMP_END_IN_M = 1.2           # a corner lamp's centre back from the walk's end at the corner
LAMP_SPACING_M = 46.0         # between corners on a business street, both sides, staggered
CORNER_REACH_M = 6.0          # a walk end this near its junction's corridor is a corner
CORNER_MERGE_M = 6.5          # two corner lamps nearer than this are one corner
POLE_KERB_INSET_M = 0.3
POLE_SPACING_M = 40.0
WIRE_MAX_M = 62.0
HITCH_KERB_INSET_M = 0.28
HITCH_SPACING_M = 7.5
CLEAR_M = 1.6                 # a hitching post this near a lamp or pole gives way
END_CLEAR_M = 3.0             # nothing but a corner lamp this near a walk's end
SHOP_REACH_M = 24.0           # an attached row within this of a walk's middle makes it a shop walk
TREE_SPACING_M = 9.1          # about 30 ft, as a planted file of street trees
TREE_KERB_INSET_M = 0.55      # a trunk's centre in from the kerb edge of the walk, in its box
TREE_GAP_SHARE = 0.3          # a young city's planting: about one place in three stands empty
TREE_YOUNG_SHARE = 0.2
TREE_END_CLEAR_M = 9.0        # clear of the corner
TREE_REACH_M = 3200.0         # from State and Madison: the residential streets a visitor walks to
STATE_MADISON = (837.9, -525.7)
HOUSE_DISTRICTS = ("south_residential", "north_residential", "west_residential", "mixed_neighborhood")


def phase(text: str) -> float:
    return int(hashlib.sha1(text.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF


def inside(p, poly) -> bool:
    x, y = p
    c = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c


def r2(v: float) -> float:
    return round(v, 2)


class Walk:
    def __init__(self, s: dict):
        self.id = s["id"]
        self.a, self.b = s["a"], s["b"]
        self.y = s["y"]
        self.w = s["width_m"]
        de, dn = self.b[0] - self.a[0], self.b[1] - self.a[1]
        self.L = math.hypot(de, dn)
        self.ue, self.un = de / self.L, dn / self.L
        m = re.search(r"_walk_(-?1)(?:_\d+)?$", self.id)
        self.side = int(m.group(1)) if m else 1
        self.run = self.id.split("__")[0]
        self.heading = (math.degrees(math.atan2(self.ue, self.un)) + 360) % 360

    def at(self, t: float, inset: float):
        """A point `t` metres along the walk, `inset` metres in from its kerb edge."""
        # The walk's centre stands at side*(half+walk/2) on the street's normal (-un, ue), so
        # its kerb edge is the other way, toward the street.
        nx, nn = -self.un, self.ue
        off = -self.side * (self.w / 2 - inset)
        return (self.a[0] + self.ue * t + nx * off, self.a[1] + self.un * t + nn * off)


def load_sources(ids):
    out = {}
    for sid in ids:
        rec = json.loads((SOURCES / f"{sid}.json").read_text())
        out[sid] = {k: rec[k] for k in ("citation", "url", "date", "tier", "rights_status") if k in rec}
    return out


def build() -> dict:
    ctx = json.loads(CONTEXT.read_text())
    lamp_kind = json.loads(LAMPS_1904.read_text())["kinds"]["gas_lamp"]
    core = ctx["street_names"]["core_polygon"]
    names = {}
    for s in ctx["streets"]:
        if s.get("name"):
            names[s["street_id"]] = s["name"]
    walks = [Walk(s) for s in ctx["walk_surfaces"] if s["kind"] == "walk"]
    walks = [w for w in walks if w.L > 2 and inside(((w.a[0] + w.b[0]) / 2, (w.a[1] + w.b[1]) / 2), core)]
    walks.sort(key=lambda w: w.id)
    # The attached shop rows, by 50 m cell, for "does this walk front shops".
    cells = defaultdict(list)
    for b in ctx["buildings"]:
        if b.get("row") == "attached":
            cells[(int(b["e"] // 50), int(b["n"] // 50))].append(b)

    def shop_district(p):
        best = None
        for i in range(int((p[0] - SHOP_REACH_M) // 50), int((p[0] + SHOP_REACH_M) // 50) + 1):
            for j in range(int((p[1] - SHOP_REACH_M) // 50), int((p[1] + SHOP_REACH_M) // 50) + 1):
                for b in cells[(i, j)]:
                    d = math.hypot(b["e"] - p[0], b["n"] - p[1])
                    if d < SHOP_REACH_M and (best is None or d < best[0]):
                        best = (d, b["district"])
        return best[1] if best else None

    allcells = defaultdict(list)
    for b in ctx["buildings"]:
        allcells[(int(b["e"] // 50), int(b["n"] // 50))].append(b)

    def house_district(p, reach=30.0):
        best = None
        for i in range(int((p[0] - reach) // 50), int((p[0] + reach) // 50) + 1):
            for j in range(int((p[1] - reach) // 50), int((p[1] + reach) // 50) + 1):
                for b in allcells[(i, j)]:
                    d = math.hypot(b["e"] - p[0], b["n"] - p[1])
                    if d < reach and (best is None or d < best[0]):
                        best = (d, b["district"])
        return best[1] if best else None

    junctions = [j for j in ctx["junctions"] if inside((j[0], j[1]), core)]
    jcell = defaultdict(list)
    for j in junctions:
        jcell[(int(j[0] // 60), int(j[1] // 60))].append(j)

    def junction_near(p, reach):
        for i in range(int((p[0] - reach) // 60), int((p[0] + reach) // 60) + 1):
            for k in range(int((p[1] - reach) // 60), int((p[1] + reach) // 60) + 1):
                for j in jcell[(i, k)]:
                    if math.hypot(j[0] - p[0], j[1] - p[1]) < reach:
                        return j
        return None

    items = []
    taken = defaultdict(list)   # 10 m cells of placed points, for the clearances

    def near_taken(p, r):
        for i in range(int((p[0] - r) // 10), int((p[0] + r) // 10) + 1):
            for k in range(int((p[1] - r) // 10), int((p[1] + r) // 10) + 1):
                for q in taken[(i, k)]:
                    if math.hypot(q[0] - p[0], q[1] - p[1]) < r:
                        return True
        return False

    def put(item, p):
        items.append(item)
        taken[(int(p[0] // 10), int(p[1] // 10))].append(p)

    street_half = {s["street_id"]: s["width_m"] / 2 + s["walk_m"] for s in ctx["streets"]}

    # 1. Corner lamps: at each walk end that stops at a named junction, one per corner.
    corner_pts = []
    for w in walks:
        reach = street_half.get(w.run, 10) + CORNER_REACH_M + 8
        for t, end in ((LAMP_END_IN_M, "a"), (w.L - LAMP_END_IN_M, "b")):
            if w.L < 2 * LAMP_END_IN_M + 1:
                continue
            tip = w.a if end == "a" else w.b
            j = junction_near(tip, reach)
            if not j:
                continue
            p = w.at(t, LAMP_KERB_INSET_M)
            if any(math.hypot(q[0] - p[0], q[1] - p[1]) < CORNER_MERGE_M for q in corner_pts):
                continue
            corner_pts.append(p)
            put({"id": f"lamp.corner.{w.id}.{end}", "kind": "gas_lamp", "e": r2(p[0]), "n": r2(p[1]),
                 "y_m": w.y, "heading_deg": r2(w.heading), "place": "corner",
                 "where": f"at the corner of {j[2]} and {j[3]}", "streets": [j[2], j[3]], "face": w.id,
                 "grade": "reconstructed", "sources": [], "liberty": LIBERTY}, p)

    shop = {w.id: shop_district(((w.a[0] + w.b[0]) / 2, (w.a[1] + w.b[1]) / 2)) for w in walks}

    # 2. Business-street lamps between the corners, the two sides staggered.
    for w in walks:
        if shop[w.id] != "central_business":
            continue
        start = LAMP_SPACING_M * (0.5 + 0.5 * (w.side > 0)) * 0.999
        t = start
        while t < w.L - 10:
            if t > 10:
                p = w.at(t, LAMP_KERB_INSET_M)
                if not near_taken(p, 12):
                    put({"id": f"lamp.walk.{w.id}.{int(t)}", "kind": "gas_lamp", "e": r2(p[0]), "n": r2(p[1]),
                         "y_m": w.y, "heading_deg": r2(w.heading), "place": "walk",
                         "where": f"on the walk of {names.get(w.run, 'a business street')}", "face": w.id,
                         "grade": "reconstructed", "sources": [], "liberty": LIBERTY}, p)
            t += LAMP_SPACING_M

    # 3. Telegraph poles down the principal business streets, on one side, and their wires.
    poles_by_run = defaultdict(list)
    for w in walks:
        name = names.get(w.run)
        if name not in TELEGRAPH_STREETS or shop[w.id] is None or w.side != 1:
            continue
        t = POLE_SPACING_M * phase(w.run)
        while t < w.L:
            if END_CLEAR_M < t < w.L - END_CLEAR_M:
                p = w.at(t, POLE_KERB_INSET_M)
                if not near_taken(p, CLEAR_M):
                    it = {"id": f"pole.telegraph.{w.id}.{int(t)}", "kind": "utility_pole", "class": "telegraph",
                          "e": r2(p[0]), "n": r2(p[1]), "y_m": w.y, "heading_deg": r2(w.heading), "place": "walk",
                          "where": f"at the kerb of {name}", "face": w.id, "grade": "reconstructed",
                          "sources": [], "liberty": LIBERTY}
                    put(it, p)
                    poles_by_run[w.run].append((p, w, it))
            t += POLE_SPACING_M
    wires = []
    for run, poles in sorted(poles_by_run.items()):
        w0 = poles[0][1]
        poles.sort(key=lambda x: (x[0][0] - w0.a[0]) * w0.ue + (x[0][1] - w0.a[1]) * w0.un)
        for (p, _, a), (q, _, b) in zip(poles, poles[1:]):
            if math.hypot(q[0] - p[0], q[1] - p[1]) <= WIRE_MAX_M:
                wires.append({"from": a["id"], "to": b["id"], "kind": "line", "grade": "reconstructed"})

    # 4. Hitching posts along the shop walks.
    for w in walks:
        if shop[w.id] not in ("central_business", "river_industry", "mixed_neighborhood",
                              "north_residential", "south_residential", "west_residential"):
            continue
        t = END_CLEAR_M + HITCH_SPACING_M * phase(w.id)
        while t < w.L - END_CLEAR_M:
            p = w.at(t, HITCH_KERB_INSET_M)
            if not near_taken(p, CLEAR_M):
                put({"id": f"hitch.{w.id}.{int(t * 10)}", "kind": "hitching_post", "e": r2(p[0]), "n": r2(p[1]),
                     "y_m": w.y, "heading_deg": r2(w.heading), "place": "walk",
                     "where": f"at the kerb of {names.get(w.run, 'a shop street')}", "face": w.id,
                     "grade": "reconstructed", "sources": [], "liberty": LIBERTY}, p)
            t += HITCH_SPACING_M

    # Short ids, numbered per kind in a fixed order (the walk ids they were laid from are long, and
    # ten thousand of them were a third of the file); the walk stays on the item as `face`.
    # 5. Street trees along the house streets (the street_trees layer draws them).
    trees = []
    for w in walks:
        mid = ((w.a[0] + w.b[0]) / 2, (w.a[1] + w.b[1]) / 2)
        if shop[w.id] is not None or math.hypot(mid[0] - STATE_MADISON[0], mid[1] - STATE_MADISON[1]) > TREE_REACH_M:
            continue
        if house_district(mid) not in HOUSE_DISTRICTS:
            continue
        t = TREE_END_CLEAR_M + TREE_SPACING_M * phase("tree" + w.id)
        k = 0
        while t < w.L - TREE_END_CLEAR_M:
            key = f"{w.id}#{k}"
            u = phase("gap" + key)
            if u >= TREE_GAP_SHARE:
                p = w.at(t + (phase("jit" + key) - 0.5) * 1.2, TREE_KERB_INSET_M)
                if not near_taken(p, CLEAR_M):
                    young = phase("young" + key) < TREE_YOUNG_SHARE
                    trees.append({"id": key, "face": w.id, "e": r2(p[0]), "n": r2(p[1]), "y_m": w.y,
                                  "kind": "young" if young else "mature", "variant": int(phase("var" + key) * 12) % 12,
                                  "yaw_deg": r2(phase("yaw" + key) * 360),
                                  "scale": r2((0.55 if young else 0.78) + phase("sc" + key) * 0.25)})
            t += TREE_SPACING_M
            k += 1
    trees.sort(key=lambda x: x["id"])
    for i, tr in enumerate(trees):
        tr["id"] = f"tree.{i:05}"
        tr.pop("face")
    trees_doc = {
        "_doc": "The 1871 city's street trees (owner, 2026-11-21). GENERATED by tools/lay_1871_street_furniture.py "
                "from data/context/1871.json -- do not hand-edit; re-run the tool. Drawn by "
                "renderers/web/js/street-trees.js. docs/LIBERTIES.md L-1871-streetscape.",
        "scene": "1871", "target_date": "1871-10-08", "ticket": TICKET,
        "generated_by": "tools/lay_1871_street_furniture.py",
        "card": {"name": "A street tree", "young_name": "A young street tree",
                 "note": "A tree in a box at the edge of the plank walk, as the city's house streets were planted by "
                         "1871. Its spot, and the kind it is drawn as, are our reconstruction.",
                 "research_doc": None},
        "species": {"id": "ulmus_americana", "common": "street tree (drawn as an American elm)", "tier": "reconstructed",
                    "sources": ["loc_stereo_1s47902_crosbys_opera_house", "loc_stereo_1s12325_court_house"],
                    "note": "Carbutt's No. 139 looks down Washington Street past the opera house to a street of tall, "
                            "broad-crowned trees, and the Court House stereograph shows the square's trees; neither "
                            "picture names the kind. Every street tree is drawn as the American elm the 1904 layer grows."},
        "placement": {"tier": "reconstructed", "liberty": LIBERTY, "spacing_ft": 30, "variants": 12,
                      "note": f"On the house streets within about {TREE_REACH_M / 1000:.1f} km of State and Madison: one file a side at about 30 ft, {TREE_KERB_INSET_M} m in from the kerb, clear of the corners, with about one place in three empty and one tree in five young, as a city planting its streets for twenty years would show. Reconstructed."},
        "summary": {"trees": len(trees), "young": sum(1 for t in trees if t["kind"] == "young")},
        "trees": trees,
    }

    items.sort(key=lambda it: it["id"])
    short = {}
    for k, prefix in (("gas_lamp", "lamp"), ("utility_pole", "pole"), ("hitching_post", "hitch")):
        for i, it in enumerate(x for x in items if x["kind"] == k):
            short[it["id"]] = f"{prefix}.{i:05}"
    for it in items:
        it["id"] = short[it["id"]]
        for key in ("sources", "liberty", "grade"):   # the file's defaults, stated once in `item_defaults`
            it.pop(key, None)
        if it["kind"] == "hitching_post":
            it.pop("face", None)
    for w in wires:
        w["from"], w["to"] = short[w["from"]], short[w["to"]]
        w.pop("grade", None)
    wires.sort(key=lambda x: (x["from"], x["to"]))
    lamp = dict(lamp_kind)
    lamp.update({
        "form_grade": "inferred",
        "form_sources": ["loc_stereo_1s47905_tremont_house", "loc_stereo_1s47902_crosbys_opera_house",
                         "loc_stereo_1s12371_sherman_house"],
        "form_note": "Carbutt's stereographs of Lake and Dearborn, Washington Street and Clark and Randolph show "
                     "cast-iron posts with a four-sided glazed lantern at the corners and before the opera house's "
                     "door, about the height of a man and a half. Every 1871 lamp is drawn with the 1904 layer's "
                     "post (data/street_furniture/1904.json, read off the 1880s Prairie Avenue photographs), the "
                     "same pattern of post and lantern; its mouldings are not read off the 1860s pictures.",
        "ticket": TICKET,
        "rule_note": "The 1860s stereographs show gas lamps at the corners of the business streets and before their doors",
    })
    kinds = {
        "gas_lamp": lamp,
        "utility_pole": {
            "name": "telegraph pole", "name_by_class": {"telegraph": "telegraph pole"},
            "form": "A wooden pole about 12 m, tapering from its butt, with five crossarms of six pins and glass insulators.",
            "form_grade": "inferred",
            "form_sources": ["loc_stereo_1s12371_sherman_house", "loc_stereo_1s47905_tremont_house"],
            "form_note": "Carbutt's No. 52 shows the Clark Street poles at the kerb with five or six crossarms and the "
                         "wires running down the street; No. 55 a tall pole with short crossarms at Lake and Dearborn. "
                         "Every pole is drawn alike.",
            "model_m": {"telegraph": {"height_m": 12.0, "butt_d_m": 0.32, "top_d_m": 0.2, "arms": 5, "pins": 6,
                                      "arm_len_m": 2.2, "arm_below_top_m": 0.4}},
            "what": "A wooden pole carrying the telegraph lines",
            "ticket": TICKET,
            "rule_note": "The 1860s stereographs show telegraph poles at the kerb of the principal business streets",
        },
        "hitching_post": {
            "name": "hitching post",
            "form": "A cast-iron post about 1.1 m, a ring at its head to tie a horse's rein to, on the walk at the kerb.",
            "form_grade": "reconstructed",
            "form_sources": ["loc_stereo_1s47902_crosbys_opera_house"],
            "form_note": "Carbutt's No. 139 shows a horse and buggy standing at the Washington Street kerb; the posts "
                         "they were tied to are too small in any of the pictures to read, so the post is the plain iron "
                         "kind of the period, reconstructed.",
            "model_m": {"height_m": 1.1, "r_m": 0.045, "cap_r_m": 0.07, "ring_r_m": 0.06},
            "what": "A post to tie a horse to",
            "ticket": TICKET,
            "rule_note": "Horses stand at the kerb in every picture of the business streets",
        },
    }
    count = defaultdict(int)
    for it in items:
        count[it["kind"]] += 1
    doc = {
        "_doc": "The 1871 city's street furniture (owner, 2026-11-21): gas lamps, telegraph poles and wires, and "
                "hitching posts. GENERATED by tools/lay_1871_street_furniture.py from data/context/1871.json -- do "
                "not hand-edit; re-run the tool. Local ENU metres of data/datum.json; heading_deg is the compass "
                "bearing of the street the item stands along; y_m is the walk's own height, which every item stands "
                "on. Drawn by renderers/web/js/street-furniture.js. docs/LIBERTIES.md L-1871-streetscape.",
        "scene": "1871", "target_date": "1871-10-08", "ticket": TICKET,
        "generated_by": "tools/lay_1871_street_furniture.py",
        "research_doc": "docs/LIBERTIES.md",
        "kinds": kinds,
        "placement": {
            "gas_lamp": {"liberty": LIBERTY, "note": f"A lamp at each corner of the platted city's named streets, on the walk {LAMP_KERB_INSET_M} m in from the kerb and {LAMP_END_IN_M} m back from the corner; on the business streets one about every {int(LAMP_SPACING_M)} m between, the two sides staggered. Reconstructed."},
            "utility_pole": {"liberty": LIBERTY, "note": f"On one side of each principal business street where it fronts shops, about every {int(POLE_SPACING_M)} m, {POLE_KERB_INSET_M} m in from the kerb; wires join neighbouring poles. Reconstructed."},
            "hitching_post": {"liberty": LIBERTY, "note": f"Along the walks that front shop rows, about every {HITCH_SPACING_M} m at the kerb, clear of the lamps and poles. Reconstructed."},
        },
        "wire_model": {"sag_frac": 0.014},
        "item_defaults": {"grade": "reconstructed", "sources": [], "liberty": LIBERTY},
        "street_names": {},
        "sources": load_sources(sorted({s for k in kinds.values() for s in k.get("form_sources", [])})),
        "summary": {"items": len(items), "gas_lamps": count["gas_lamp"], "telegraph_poles": count["utility_pole"],
                    "hitching_posts": count["hitching_post"], "wires": len(wires), "corner_lamps": len(corner_pts)},
        "items": items,
        "wires": wires,
    }
    return doc, trees_doc


def encode(doc: dict) -> str:
    return json.dumps(doc, separators=(",", ":"), ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    doc, trees = build()
    outs = ((OUT, encode(doc)), (TREES_OUT, encode(trees)))
    if args.check:
        stale = [p for p, text in outs if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"STALE: {p.relative_to(ROOT)} is not what tools/lay_1871_street_furniture.py writes; re-run it")
        if stale:
            return 1
        print("OK: data/street_furniture/1871.json and data/street_trees/1871.json are current")
        return 0
    for p, text in outs:
        p.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} — {doc['summary']}")
    print(f"wrote {TREES_OUT.relative_to(ROOT)} — {trees['summary']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
