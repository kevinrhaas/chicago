#!/usr/bin/env python3
"""Lay the 1871 city's street furniture: gas lamps, telegraph poles and wires, and hitching
posts along the shop walks (the owner, 2026-11-21).

    python3 tools/lay_1871_street_furniture.py           # write data/street_furniture/1871.json
    python3 tools/lay_1871_street_furniture.py --check   # the committed file is what this writes
    python3 tools/lay_1871_street_furniture.py --self-test  # the furniture check refuses what it must (T-3805)

The owner, 2026-11-21: "I think we need trees and other streetscape, analyze street scenes
from the era and add the correct supporting street furniture and other appropriate items
around the businesses and houses and on the streets".

WHAT THE PICTURES SHOW. The stereographs of the downtown streets the scene already cites,
read for what stands on the walks rather than for the buildings they were solved on:

  * Carbutt's No. 55 (LOC 1s47905), Lake and Dearborn: a cast-iron gas lamp post at the
    corner, on the walk at the kerb, beside a tall wooden pole with short crossarms; barrels
    on the far corner's walk; awnings down Lake Street.
  * Carbutt's No. 52 (LOC 1s12371), Clark and Randolph: a gas lamp at the corner of the
    square, telegraph poles of five or six crossarms on the kerb of Clark Street with their
    wires down the street, a stand of closed hacks at the square's kerb.
  * Carbutt's No. 139 (LOC 1s47902), Washington Street: a pair of lamp posts at the opera
    house's door, a horse and buggy standing at the kerb.

So: a lamp at the corners, the lamps of the business streets between corners, the telegraph
lines down the principal business streets on poles at the kerb, and posts to tie a horse to
along the shop walks, where every picture has a horse standing.

WHAT IT READS. data/context/1871.json (generated by generators/city_1871_emit.py): its walk
surfaces (each raised plank walk's centreline, width and height), its named junctions, its
core polygon, and its buildings (which walks front attached shop rows, and in which district).
The source records the kinds cite are copied in from data/sources/, so a card can show them.

GRADES. The kinds' forms are inferred from the pictures (the lamp post is the 1904 layer's
cast-iron post, the same pattern of post and lantern the 1860s pictures show at the corners);
the hitching post's form is reconstructed. Every item's place is reconstructed: the pictures
show that such things stood at such places, not where each one stood. docs/LIBERTIES.md
L-1871-streetscape is the record. Deterministic: no randomness but a fixed per-walk phase.
"""
