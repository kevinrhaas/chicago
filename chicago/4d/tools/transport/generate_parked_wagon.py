"""Generate/verify the single parked W01 refinement; no cached GLB inputs."""
from pathlib import Path
import argparse,hashlib,json,subprocess,sys,tempfile,struct
P=Path(__file__).resolve().parent
S=P/'wagon_parked'
def need(c,m):
    if not c:raise ValueError(m)
def sha(data):return hashlib.sha256(data).hexdigest()
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--parameters',type=Path,required=True)
    p.add_argument('--output-dir',type=Path,required=True)
    p.add_argument('--texture-output-dir',type=Path)
    p.add_argument('--verify',action='store_true')
    a=p.parse_args();cfg=json.loads(a.parameters.read_text())
    need(cfg['schema']=='parked_wagon_w01_finish_v1','Explicit recipe required')
    need(cfg['expected_glb_sha256']=='274e737b51872983df792d0b24de8e75de8631890a8d586a32d9c6f0066484fb','Reviewed optical candidate required')
    with tempfile.TemporaryDirectory(prefix='parked-w01-') as tmp:
        t=Path(tmp)
        for name,contents in [('hardware',cfg['base_study']['hardware_parameters']),('material',cfg['base_study']['materials']),('finish',cfg['finish'])]:
            (t/(name+'.json')).write_text(json.dumps(contents,indent=2)+'\n' if name=='finish' else json.dumps(contents))
        commands=[
            [str(S/'generate_wagon_hardware.py'),'--parameters',str(t/'hardware.json'),'--output-dir',str(t/'hardware')],
            [str(S/'apply_materials.py'),'--vehicle',str(t/'hardware/wagon-w01.glb'),'--parts',str(t/'hardware/authored-parts.json'),'--parameters',str(t/'material.json'),'--output',str(t/'material')],
            [str(S/'refine_materials.py'),'--parent',str(t/'material/wagon-w01.glb'),'--parameters',str(t/'finish.json'),'--output',str(t/'finish')],
        ]
        for command in commands:
            result=subprocess.run([sys.executable,*command],text=True,capture_output=True)
            need(result.returncode==0,'Generation failed: '+result.stderr[-6000:])
        raw=(t/'finish/wagon-w01.glb').read_bytes()
        need(sha(raw)==cfg['expected_glb_sha256'],'Generated bytes differ from reviewed candidate')
        n=struct.unpack_from('<I',raw,12)[0];g=json.loads(raw[20:20+n])
        metadata=dict(g['extras'])
        metadata.update(asset_id=cfg['asset_id'],geometry_family_asset_id=g['extras']['asset_id'],glb_sha256=sha(raw),
          status='original reconstructed parked wagon; photographic and period-finish acceptance open',
          recipe_sha256=sha(a.parameters.read_bytes()),
          source_sha256={'generate_parked_wagon.py':sha(Path(__file__).read_bytes()),**{v.name:sha(v.read_bytes()) for v in sorted(S.iterdir()) if v.is_file() and v.suffix in ['.py','.json']}},
          license='GPL-3.0-or-later geometry; CC0-1.0 original procedural pixels',
          texture_memory_estimate={'RGBA8_plus_mips_bytes':6291456,'scope':'embedded-image dimension estimate, not measured GPU allocation'},
          parked_tongue={'joint':'vehicle_tongue','flat_ground_rotation_x_rad':0.18578444683082146,'scope':'minimum of every actual timber/iron vertex; adjust for actual terrain after placement'},
          limitations=['No known Chicago wagon or owner identified','Body dimensions, hardware form, timber and paint colors are reconstructed','Flat endgrain/hubs and coarse edge form remain unresolved','No loading, forces, occupied driver, rolling or photographic acceptance'])
        products={'wagon-w01.glb':raw,'wagon-w01.json':(json.dumps(metadata,indent=2,sort_keys=True)+'\n').encode()}
        if a.texture_output_dir:
            products.update({str(a.texture_output_dir/v.name):v.read_bytes() for v in sorted((t/'finish/textures').glob('*.png'))})
        for name,data in products.items():
            target=Path(name) if '/' in name else a.output_dir/name
            if a.verify:
                need(target.is_file() and target.read_bytes()==data,'Stale or missing output '+str(target))
            else:
                target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
        print(json.dumps({'verified':a.verify,'asset_id':cfg['asset_id'],'glb_sha256':sha(raw),'triangles':12104,'draw_batches':23,'texture_RGBA8_mip_bytes':6291456}))
if __name__=='__main__':main()
