#!/usr/bin/env python3
"""T-3684: the clip of the City's street centrelines the 1871 city is drawn on.

    python3 tools/build_streets_1871.py --source Transportation.geojson --write
    python3 tools/build_streets_1871.py --check    the committed clip holds its shape

WHY A MODERN FILE DRAWS AN 1871 STREET. Inside the old city -- Halsted Street to the
lake, Twenty-second Street to North Avenue -- the streets of 1871 were the streets of
the plats (the original town of 1830, Kinzie's and Wolcott's additions, the School
Section, the canal trustees' subdivisions), and those lines have not moved since. The
1870 Mitchell map (data/context/1871/plan.json map_control: 18.7 m RMS) draws every
one of them, but it is too coarse to trace a block from. So the LINE is taken from
the City's own centreline file (source chicago_street_center_lines, the same release
data/modern/streets.json clips, by the same reader in tools/build_modern_streets.py)
and the NAME and the street's existence come from 1870-71 sources, through
data/context/1871/street_names_1871.json: every modern name in this clip is either
given its 1871 name with the evidence for it, or dropped because the street is later
than 1871 (Wacker Drive, Columbus Drive, the expressways, the made land east of the
1871 shore). The few lines that moved -- South Water Street under Wacker Drive -- are
drawn from their 1835 records instead (generators/city_1871_emit.py). The clip is a
navigation-grade line, not a survey: streets were widened, and an 1871 kerb is a
reconstruction (docs/LIBERTIES.md L-1871-street-network).

This clip is a larger box than data/modern/streets.json (which serves the Today line
of 1812, 1835 and 1904 and keeps its own box); the reader, the filters and the
simplification are the same functions.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build_modern_streets as modern  # noqa: E402

OUT = ROOT / "data" / "context" / "1871" / "modern_clip.json"
BOX = (-900.0, -3900.0, 2700.0, 2800.0)


def build(source: Path) -> dict:
    modern.BOX = BOX
    doc = modern.build(source)
    doc.pop("_doc", None)
    doc["_doc"] = ("T-3684: the City's street centrelines clipped to the 1871 inner city, the "
                   "lines the 1871 streets are drawn on. Generated by "
                   "tools/build_streets_1871.py --write from the source file; names here are "
                   "TODAY's, and data/context/1871/street_names_1871.json carries each to its "
                   "1871 name or drops it. See the tool's docstring.")
    doc["ticket"] = "T-3684"
    doc["generated_by"] = "tools/build_streets_1871.py --write"
    return doc


def check(doc: dict) -> list[str]:
    errs = []
    if doc.get("box_local_m") != list(BOX):
        errs.append("box differs from the tool's BOX: rerun --write")
    names, segs = doc.get("names") or [], doc.get("segments") or []
    if doc.get("counts") != {"segments": len(segs), "names": len(names)}:
        errs.append("counts disagree with the file")
    if len(segs) < 1500:
        errs.append(f"only {len(segs)} segments: the clip has lost the city")
    if doc.get("source") != modern.SOURCE_ID:
        errs.append("source is not the City's centreline file")
    return errs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=Path)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.write:
        if not a.source:
            ap.error("--write needs --source Transportation.geojson")
        doc = build(a.source)
        OUT.write_text(json.dumps(doc, separators=(",", ":")) + "\n")
        print(f"wrote {OUT.relative_to(ROOT)}: {doc['counts']}")
        return 0
    errs = check(json.loads(OUT.read_text()))
    for e in errs:
        print("FAIL", e)
    if not errs:
        print("1871 street clip OK")
    return 1 if errs else 0


if __name__ == "__main__":
    raise SystemExit(main())
