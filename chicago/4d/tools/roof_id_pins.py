#!/usr/bin/env python3
"""ONE LIST OF THE NAMES A ROOF-ID SWEEP MAY NOT MOVE. T-1499.

    tools/roof_id_pins.py --list       every pin, its category and its reason
    tools/roof_id_pins.py --check      the two sweeps agree, and every pin is earned
    tools/roof_id_pins.py --self-test  the guards, fired on fixtures

TWO TOOLS SWEEP THE SAME SURFACE. `tools/migrate_roof_ids.py` carries the phase-one
South parcel's ids across the committed tree; `tools/execute_roof_redeal.py
--check-migration` asks of the North Division parcel's whether any committed file
still names one. Both put the same question to the same file --- may this one keep
the old name? --- and until this module each kept its own answer: `KEEPS_THE_OLD_NAME`
in the first and `MIGRATION_PINNED` in the second, with overlapping contents and the
same reasoning written out twice.

WHY THAT MATTERED MORE THAN THE DUPLICATION. The two lists could DISAGREE, and a
disagreement was silent in the direction that hurts. A file pinned in one sweep and
not the other is red on whichever gate happens to run, and a file that should be
stale but is pinned in both is a dangling id nothing catches --- and a dangling id in
an enclosure or a signage run reads as a record about a building the scene does not
draw. The only thing keeping the two in agreement was that somebody edited both, and
twice nobody did: `tools/measure_roof_id_migration.py` had to be added to the first
list on #1588 and, an hour later and for word-for-word the same reason, to the second
on #1596. Each addition was made because a gate went red, not because anybody noticed
the other list.

THE DIVERGENCES THIS MODULE CLOSED, measured on the committed tree on 2026-09-21.
Six, and every one of them was a file one sweep would have rewritten and the other
would have refused to:

  * `tickets/`, `patches/`, `*.log` and `*.patch` --- pinned by the executor, not by
    the migrator. This is the divergence T-1499 demonstrated while it was being
    FILED: its own first draft quoted a migrated id, as the executor's prose does,
    and one sweep accepted the file while the other refused it, on the same tree, for
    the same text.
  * `tools/migrate_roof_ids.py`, `data/reconstruction/1835_phase2_west_wolf_point_approaches.json`
    and `renderers/web/js/changelog.js` --- pinned by the migrator, not by the
    executor.
  * `docs/unreal/prototype/` --- pinned whole by the executor, and by one named file
    inside it by the migrator.
  * `data/reconstruction/1835_north_division_initial_parcel.json` --- not in either
    LIST. The executor skipped it inline, two branches apart from the list, with its
    reason in a trailing comment; the migrator did not know about it at all. It is a
    pin, and it is written down here as one.

THE UNION IS THE CONSOLIDATION, AND IT MOVES NOTHING. Every one of those six is a
file added to the pinned set of the sweep that lacked it, so each sweep now exempts
MORE than it did, never less. A wider exemption can only turn a red gate green; it
cannot turn a green one red, and it cannot rewrite a name that was being rewritten
before. That is why this is a consolidation rather than a re-migration, and why no
committed record changes as a result of it.

WHAT THE GATE ASKS, and each of the four is a silence the old arrangement had:

  1. THE TWO SWEEPS AGREE. Both tools are imported and asked their own verdict for
     every file in the source tree, and an answer that differs from this module's is
     a red gate. A future run that re-introduces a private list inside one sweep does
     not quietly diverge; it fails here.
  2. NO PIN IS DEAD. A pin that matches no committed path is a typo or a file that
     has moved, and either way it is an exemption nobody can see the effect of.
  3. EVERY PIN IS EARNED. A pin declares a CATEGORY, and a category declares the
     scope of the tree a name of that kind may live in. Every committed file a pin
     matches must lie inside its category's scope --- so pinning `data/sidecars/`
     as a dated receipt is refused, because a sidecar is not under a receipts path.
     Adding a pin that is none of the recognised kinds therefore costs an argument:
     a new category, written down and reviewable, rather than one more line in a
     tuple.
  4. A RE-DERIVED FILE IS NEVER PINNED. `REDERIVED` is a different idea and it must
     stay one. Those files name every migrated roof and they are the measurement of
     whether the migration worked; a rewritten ledger would agree with the migration
     by construction, so they are REGENERATED by the tool that writes them. Pinning
     one would mean "leave the old name standing", which is the opposite instruction.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TICKET = "T-1499"

# Not the source tree: a build output, a dependency, and the published mirror. No
# sweep descends into these, and the agreement below is not asked about them.
NOT_THE_SOURCE_TREE = (".git/", "node_modules/", "site/")


@dataclass(frozen=True)
class Category:
    """A KIND of written name that is true as written, and where one may live.

    `scope` is the answer to "where in this tree could a name of this kind be?" and
    it is what makes a pin arguable rather than assertable: a pin may only reach
    files inside its category's scope, so a new exemption has to say what kind of
    thing it is and be right about it.
    """

    key: str
    name: str
    why: str
    scope: tuple[str, ...]


@dataclass(frozen=True)
class Pin:
    """One path prefix (or `*<suffix>`) the sweeps leave alone, and its reason."""

    match: str
    category: str
    reason: str


# The categories both lists already recognised, kept and named. The words are theirs.
