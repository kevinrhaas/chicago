# --------------------------------------------------------------------------
# the question both sweeps ask
# --------------------------------------------------------------------------

def matches(rule: str, rel: str) -> bool:
    """`*<suffix>` matches on the extension, anything else is a path prefix.

    Prefix and not equality, because every pin that names a directory means the
    whole of it — which is also the semantics the two `str.startswith(tuple)` calls
    this module replaces already had.
    """
    if rule.startswith("*"):
        return rel.lower().endswith(rule[1:].lower())
    return rel.startswith(rule)


def pin_for(rel: str) -> Pin | None:
    """The pin that exempts this path, or None. The first match wins and they are
    disjoint in practice; `--check` does not depend on which one answers."""
    for pin in PINS:
        if matches(pin.match, rel):
            return pin
    return None


def is_pinned(rel: str) -> bool:
    """May this file keep a roof id that has been migrated? The whole question."""
    return pin_for(rel) is not None


def source_files() -> list[str]:
    """Every committed path a sweep could reach, as a repo-relative posix string."""
    out = []
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith(NOT_THE_SOURCE_TREE):
            continue
        out.append(rel)
    return sorted(out)


# --------------------------------------------------------------------------
# the gate
# --------------------------------------------------------------------------

def earned(tree: list[str]) -> list[str]:
    """Every committed file a pin reaches lies inside its category's scope."""
    faults = []
    for pin in PINS:
        cat = CATEGORY.get(pin.category)
        if cat is None:
            faults.append(f"{pin.match} claims the category {pin.category!r}, "
                          f"which is not one this module recognises")
            continue
        reached = [rel for rel in tree if matches(pin.match, rel)]
        if not reached:
            faults.append(f"{pin.match} is a dead pin — no committed file matches "
                          f"it, so its exemption cannot be seen to do anything")
            continue
        outside = [rel for rel in reached
                   if not any(matches(s, rel) for s in cat.scope)]
        if outside:
            faults.append(
                f"{pin.match} is pinned as {cat.name!r}, whose scope is "
                f"{', '.join(cat.scope)} — but it reaches {len(outside)} file(s) "
                f"outside it, the first being {outside[0]}")
    return faults


def disjoint() -> list[str]:
    """A re-derived file is never pinned."""
    return [f"{rel} is both pinned and re-derived — a pin says 'keep the old name' "
            f"and a re-derivation says 'regenerate until it holds the new one'"
            for rel in REDERIVED if is_pinned(rel)]


def agree(tree: list[str]) -> list[str]:
    """Both sweeps return this module's verdict, for every file in the tree.

    Imported here and not at module scope: each sweep imports this module, so the
    import is deferred to the moment the question is actually asked.
    """
    sys.path.insert(0, str(ROOT / "tools"))
    import execute_roof_redeal  # noqa: PLC0415
    import migrate_roof_ids  # noqa: PLC0415

    sweeps = (("tools/migrate_roof_ids.py", migrate_roof_ids.keeps_the_old_name),
              ("tools/execute_roof_redeal.py", execute_roof_redeal.keeps_the_old_name))
    faults = []
    for name, verdict in sweeps:
        differs = [rel for rel in tree if bool(verdict(rel)) != is_pinned(rel)]
        if differs:
            faults.append(f"{name} disagrees with the shared list on "
                          f"{len(differs)} file(s), the first being {differs[0]} "
                          f"(it says {bool(verdict(differs[0]))}, the list says "
                          f"{is_pinned(differs[0])})")
    return faults


def shared():
    """The module object the two sweeps actually read.

    Run as a script this file is `__main__` and `roof_id_pins` is a SECOND import of
    the same source, with its own `PINS`. A mutation test that bent `__main__`'s copy
    would be asking the sweeps about a list they have never seen — and would pass
    while proving nothing — so the self-test below bends this one.
    """
    sys.path.insert(0, str(ROOT / "tools"))
    import roof_id_pins  # noqa: PLC0415
    return roof_id_pins


def check() -> int:
    tree = source_files()
    faults = agree(tree) + earned(tree) + disjoint()
    if faults:
        print("ROOF-ID PIN LIST")
        for f in faults:
            print(f"  - {f}")
        return 1
    empty = [c.name for c in CATEGORIES
             if not any(p.category == c.key for p in PINS)]
    print(f"{len(PINS)} pin(s) in {len(CATEGORIES)} category(ies), every one earned, "
          f"and both sweeps return the same verdict for all {len(tree)} source files")
    for name in empty:
        print(f"  recognised and unused today: {name}")
    return 0


def show() -> int:
    for cat in CATEGORIES:
        pins = [p for p in PINS if p.category == cat.key]
        print(f"{cat.name} — {cat.why}")
        print(f"    scope: {', '.join(cat.scope)}")
        for pin in pins:
            print(f"  * {pin.match}")
            print(f"      {pin.reason}")
        if not pins:
            print("  * (no pin today — the sweeps move a name of this kind with the "
                  "roof rather than pinning it)")
        print()
    return 0


def self_test() -> int:
    mod = shared()
    fired = 0

    assert mod.matches("tickets/", "tickets/T-0001-a.md")
    assert not mod.matches("tickets/", "tools/tickets_report.py")
    assert mod.matches("*.log", "docs/unreal/prototype/build.LOG")
    assert not mod.matches("*.log", "docs/logbook.md")
    fired += 1

    # THE DIVERGENCE THAT FILED THIS TICKET, asserted rather than remembered: a
    # ticket file naming a migrated id is pinned, and it is pinned for BOTH sweeps
    # because there is now only one answer to give.
    assert mod.is_pinned("tickets/T-1499-two-tools.md")
    assert mod.is_pinned("renderers/web/js/changelog.js")
    assert mod.is_pinned("data/reconstruction/1835_north_division_initial_parcel.json")
    assert not mod.is_pinned("data/sidecars/1835/index.json")
    fired += 1

    tree = ["tickets/T-0001-a.md", "data/sidecars/1835/index.json",
            "renderers/unreal/receipts/r.json"]
    assert not mod.agree(tree)
    fired += 1

    keep = mod.PINS

    # MUTATION ONE — remove an entry, and BOTH sweeps report the same file. The
    # agreement holds in the changed state too, which is the property that matters:
    # the two sweeps cannot diverge, not even when the list is wrong.
    try:
        mod.PINS = tuple(p for p in keep if p.match != "tickets/")
        assert not mod.is_pinned("tickets/T-0001-a.md")
        assert not mod.agree(tree), mod.agree(tree)
    finally:
        mod.PINS = keep
    assert mod.is_pinned("tickets/T-0001-a.md")
    fired += 1

    # MUTATION TWO — pin a file that should be stale, and the gate refuses it. A
    # sidecar is compiled from the structure records: it holds a live pointer at a
    # roof, and it is not a receipt of anything.
    tree_now = mod.source_files()
    try:
        mod.PINS = keep + (mod.Pin("data/sidecars/", "receipt", "it is not"),)
        faults = mod.earned(tree_now)
        assert any("data/sidecars/" in f and "dated receipt" in f for f in faults), faults
    finally:
        mod.PINS = keep
    assert not mod.earned(tree_now)
    fired += 1

    # A pin that names nothing is an exemption nobody can see the effect of.
    try:
        mod.PINS = keep + (mod.Pin("data/reconstruction/no_such_recipe.json",
                                   "recipe_record", "it does not exist"),)
        assert any("dead pin" in f for f in mod.earned(tree_now))
    finally:
        mod.PINS = keep
    fired += 1

    # A category nothing recognises is refused rather than silently ignored.
    try:
        mod.PINS = keep + (mod.Pin("docs/", "not_a_category", "invented"),)
        assert any("not one this module recognises" in f
                   for f in mod.earned(tree_now))
    finally:
        mod.PINS = keep
    fired += 1

    # THE THIRD IDEA STAYS A THIRD IDEA.
    try:
        mod.PINS = keep + (mod.Pin(mod.REDERIVED[0], "recipe_record",
                                   "it is re-derived"),)
        assert mod.disjoint(), "a re-derived file was pinned and nothing said so"
    finally:
        mod.PINS = keep
    assert not mod.disjoint()
    fired += 1

    print(f"roof_id_pins self-test: {fired} guard(s) fired")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        return self_test()
    if args.check:
        return check()
    return show()


if __name__ == "__main__":
    raise SystemExit(main())
