/**
 * site_films_ingest.mjs — take films cut by site_films.mjs into the public site.
 *
 *   node tools/site_films_ingest.mjs DIR [id ...]     ingest DIR/<id>.mp4 (+ DIR/<id>.jpg poster)
 *   node tools/site_films_ingest.mjs --check          films.js, site-films/ and the posters agree
 *
 * Each film is copied to site-films/<id>.<sha8>.mp4 (repository root, never published by
 * deploy.yml; .github/workflows/chicago-site-films.yml uploads it to the media host), any
 * older cut of the same id is removed, its poster goes to site/media/films/<id>.jpg, and
 * site/js/films.js is rewritten to name the exact files.
 *
 * A film drawn at under 20 fps (a 1904 frame costs ~25 s under SwiftShader, so the slow
 * years are drawn at 12) is motion-interpolated to 24 fps here. The camera moves are slow
 * and smooth, so the in-between frames hold up; people and horses still move at their
 * true speed, because the virtual clock advanced 1/12 s per drawn frame.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../../..');
const STORE = path.join(REPO, 'site-films');
const POSTERS = path.join(REPO, 'site/media/films');
const MANIFEST = path.join(REPO, 'site/js/films.js');
const HOSTING = JSON.parse(fs.readFileSync(path.join(HERE, 'audio-hosting.json'), 'utf8'));
const NAME = /^([a-z0-9-]+)\.([0-9a-f]{8})\.mp4$/;

function stored() {
  const out = {};
  for (const f of fs.existsSync(STORE) ? fs.readdirSync(STORE) : []) {
    const m = NAME.exec(f); if (m) out[m[1]] = f;
  }
  return out;
}
function writeManifest(files) {
  const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
  const body = `/* GENERATED by chicago/4d/tools/site_films_ingest.mjs: the public site's films.
   The MP4s live in site-films/ (never published to Pages) and are uploaded to the media host by
   .github/workflows/chicago-site-films.yml; each name carries a hash of its bytes. */
window.CHICAGO_FILMS = ${JSON.stringify({ base: `${HOSTING.public_base}site/films/`, localBase: '/site-films/', files: sorted }, null, 2)};
`;
  fs.writeFileSync(MANIFEST, body);
}

const argv = process.argv.slice(2);
if (argv[0] === '--check') {
  const files = stored();
  globalThis.window = {};
  await import(`${MANIFEST}?t=${Date.now()}`).catch(() => {});
  const listed = globalThis.window.CHICAGO_FILMS?.files ?? {};
  const bad = [];
  for (const [id, f] of Object.entries(listed)) {
    if (files[id] !== f) bad.push(`${id}: films.js names ${f}, site-films/ holds ${files[id] ?? 'nothing'}`);
    if (!fs.existsSync(path.join(POSTERS, `${id}.jpg`))) bad.push(`${id}: no poster site/media/films/${id}.jpg`);
    const sha = crypto.createHash('sha256').update(fs.readFileSync(path.join(STORE, f))).digest('hex').slice(0, 8);
    if (!f.includes(`.${sha}.`)) bad.push(`${id}: ${f} does not hash to ${sha}`);
  }
  for (const id of Object.keys(files)) if (!listed[id]) bad.push(`${id}: in site-films/ but not in films.js`);
  if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
  console.log(`site films: ${Object.keys(listed).length} films, manifest, store and posters agree`);
  process.exit(0);
}

const dir = path.resolve(argv[0] ?? '');
if (!argv[0] || !fs.existsSync(dir)) { console.error('usage: node tools/site_films_ingest.mjs DIR [id ...] | --check'); process.exit(2); }
const ids = argv.slice(1).length ? argv.slice(1) : fs.readdirSync(dir).filter(f => f.endsWith('.mp4')).map(f => f.slice(0, -4));
fs.mkdirSync(STORE, { recursive: true });
fs.mkdirSync(POSTERS, { recursive: true });
const files = stored();
for (const id of ids) {
  let src = path.join(dir, `${id}.mp4`);
  const rate = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=r_frame_rate',
    '-of', 'csv=p=0', src], { encoding: 'utf8' }).trim().split('/').map(Number);
  if (rate[0] / (rate[1] || 1) < 20) {
    const smooth = path.join(dir, `${id}.24fps.mp4`);
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', src, '-vf', 'minterpolate=fps=24:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:vsbmc=1',
      '-c:v', 'libx264', '-profile:v', 'high', '-pix_fmt', 'yuv420p', '-crf', '26', '-preset', 'slow', '-movflags', '+faststart', '-an', smooth]);
    src = smooth;
  }
  const bytes = fs.readFileSync(src);
  const sha = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 8);
  const name = `${id}.${sha}.mp4`;
  if (files[id] && files[id] !== name) fs.rmSync(path.join(STORE, files[id]));
  fs.writeFileSync(path.join(STORE, name), bytes);
  files[id] = name;
  const poster = path.join(dir, `${id}.jpg`);
  if (fs.existsSync(poster)) fs.copyFileSync(poster, path.join(POSTERS, `${id}.jpg`));
  console.log(`${id}: ${name} (${(bytes.length / 1048576).toFixed(2)} MiB)`);
}
writeManifest(files);
