#!/usr/bin/env python3
"""T-2495: generate the outer 1904 coast, apron GLB and connected railway.

Talbot 1904 locates the corridor and mainland edge. Individual tracks and grades
are reconstructed. The Sanborn-derived core files are inputs, never rewritten.
Run normally to generate; --check compares every output and checks joins/clearance.
"""
from pathlib import Path
import json, math, struct, sys
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
HF = ROOT / 'data/terrain/epochs/e1871_postfire'
OUT = HF / 'context.json'
RAIL = ROOT / 'data/railway/1904_context.json'
GLB = HF / 'context_ground.glb'
SPEC = HF / 'context_spec.json'


def interp(points, n):
    """E at N on an EN line, clamped beyond the mapped reach."""
    p = sorted(points, key=lambda p: p[1])
    return float(np.interp(n, [q[1] for q in p], [q[0] for q in p]))


class Ground:
    def __init__(self, doc=None):
        self.meta = json.loads((HF / 'heightfield.json').read_text())
        m = self.meta
        self.h = np.fromfile(HF / m['bin'], dtype='<i2').reshape(m['rows'], m['cols']) * m['scale'] + m['offset']
        self.e0, self.n0 = m['origin_e'], m['origin_n']
        self.e1 = self.e0 + (m['cols'] - 1) * m['cell_m']
        self.n1 = self.n0 + (m['rows'] - 1) * m['cell_m']
        self.doc = doc

    def shift(self, n):
        if self.n0 <= n <= self.n1 or not self.doc:
            return 0.0
        side = 'north' if n > self.n1 else 'south'
        d = self.doc[side]
        if not hasattr(self, '_lines'):
            self._lines = {}
            for name in ('north', 'south'):
                line = sorted(self.doc[name]['shoreline_local_m'], key=lambda p: p[1])
                self._lines[name] = ([p[1] for p in line], [p[0] for p in line])
        ns, es = self._lines[side]
        return float(np.interp(n, ns, es)) - d['join_shore_e']

    def sample(self, e, n):
        e -= self.shift(n)
        m = self.meta
        x = max(0, min(m['cols'] - 1, (e - self.e0) / m['cell_m']))
        y = max(0, min(m['rows'] - 1, (n - self.n0) / m['cell_m']))
        c, r = min(int(x), m['cols'] - 2), min(int(y), m['rows'] - 2)
        u, v = x - c, y - r
        return float((self.h[r,c]*(1-u)+self.h[r,c+1]*u)*(1-v)+(self.h[r+1,c]*(1-u)+self.h[r+1,c+1]*u)*v)


def fit_and_lines(spec):
    controls = json.loads((ROOT / 'data/traces/prairie_1904_control.json').read_text())['crossings']
    picks = spec['control_pixels']
    a = np.array([[*p, 1] for p in picks.values()])
    b = np.array([[controls[k]['local_e'], controls[k]['local_n']] for k in picks])
    fit = np.linalg.lstsq(a,b,rcond=None)[0]
    local = lambda p: (np.array([*p,1]) @ fit).tolist()
    rail = list(map(local, spec['rail_pixels']))
    shore = list(map(local, spec['shore_pixels']))
    s = spec['south_continuation']
    tie = np.array(local(s['north_tie_pixel']))
    def south(p):
        return (tie + (np.array(p)-np.array(s['southeast_tie_pixel'])) @ fit[:2]).tolist()
    rail += list(map(south, s['rail_pixels'][1:]))
    shore += list(map(south, s['shore_pixels'][1:]))
    # LAPACK CPU kernels disagree in the last few bits of this fit. Record its
    # coefficients at 1e-8 m/pixel (linear terms) / m (translation), far below
    # the map's 40 m working uncertainty. Geometry still uses the unrounded fit
    # above and the existing station rounding; every output is checked bytewise.
    coefficients = [[round(float(v), 8) for v in row] for row in fit]
    return rail, shore, {'coefficients':coefficients, 'residual_m':np.linalg.norm(a@fit-b,axis=1).round(2).tolist(),
                         'working_uncertainty_m':40, 'note':spec['control_note']}


def dumps(x):
    return json.dumps(x,indent=1,ensure_ascii=False)+'\n'


def build():
    spec = json.loads(SPEC.read_text())
    rail, shore, fit = fit_and_lines(spec)
    base = json.loads((ROOT/'data/railway/1904.json').read_text())
    ground = Ground()
    density = float((ROOT/'renderers/web/js/world.js').read_text().split('const HAZE_DENSITY = ')[1].split(';')[0])
    reach = math.sqrt(math.log(255))/density
    datum = json.loads((ROOT/'data/datum.json').read_text())
    coast = json.loads((HF/'shoreline.geojson').read_text())['features'][0]['geometry']['coordinates']
    ends = {name: [p[0]-datum['origin_utm_e'],p[1]-datum['origin_utm_n']]
            for name,p in [('north',coast[0]),('south',coast[-1])]}
    doc = {'_doc':'GENERATED by tools/extend_ic_lakefront_1904.py. Historical map alignment with reconstructed joins, grade and track fan. Core heightfield unchanged.',
           'ticket':'T-2495','source':spec['source'],'sources':[spec['source'],'osm_streets_2026'],
           'confidence':'reconstructed','liberty':spec['liberty'],'registration':fit,
           'map_n_m':[ground.n0-reach, ground.n1+reach], 'ground_glb':'context_ground.glb',
           'grade_note':'Boundary cross sections carried along the mapped shore. No historical level survey; reconstructed. The sampler and GLB use the same cross sections.',
           'rail_bounds':[]}
    extension = {}
    for side, boundary, limit, idx in [('north',ground.n1,ground.n1+reach,0),('south',ground.n0,ground.n0-reach,-1)]:
        sign = 1 if side=='north' else -1
        def inside(n): return 0 <= sign*(n-boundary) <= abs(limit-boundary)
        ns = {boundary,limit}
        ns.update(boundary+sign*d for d in np.arange(spec['step_m'],abs(limit-boundary),spec['step_m']))
        ns.update(n for _,n in shore+rail if inside(n))
        ns = sorted(ns,reverse=True)
        join_e = ends[side][0]
        near = sorted([t for t in base['tracks'] if abs(t['centreline_local_m'][idx][1]-boundary)<0.1],
                      key=lambda t:t['centreline_local_m'][idx][0])
        assert near, side+' has no connected tracks'
        mean = sum(t['centreline_local_m'][idx][0] for t in near)/len(near)
        core_coast_delta = join_e-interp(shore,boundary)
        core_rail_delta = mean-interp(rail,boundary)
        def blend(n):
            f=min(1,abs(n-boundary)/spec['join_m']);return f*f*(3-2*f)
        line = [[round(interp(shore,n)+core_coast_delta*(1-blend(n)),4),round(n,4)] for n in ns]
        doc[side]={'join_n':boundary,'join_shore_e':join_e,'shoreline_local_m':line,
                   'note':'Map outline joined over 160 m to the detailed tile. '+spec['shore_note']}
        tracks=[]
        for j,t in enumerate(near):
            start=t['centreline_local_m'][idx][0]
            off=(j-(len(near)-1)/2)*spec['track_spacing_m']
            points=[]
            for n in ns:
                f=blend(n)
                centre=interp(rail,n)+core_rail_delta*(1-f)
                e=centre+(start-mean)*(1-f)+off*f
                # The small scale map is not precise enough to put a track on a bank.
                # Keep the whole inherited fan inland; do not drop any through track.
                east=centre+max((len(near)-1)/2*spec['track_spacing_m'],max(q['centreline_local_m'][idx][0] for q in near)-mean)
                reserve=12.0
                coast_e=interp(line,n)
                correction=max(0,east+reserve-coast_e)*f
                points.append([round(e-correction,2),round(n,4)])
            tracks.append({'id':t['id']+'_'+side,'connects_to':t['id'],'centreline_local_m':points,
                           'length_m':round(math.fsum(math.dist(a,b) for a,b in zip(points,points[1:])),1),
                           'geometry_tier':'reconstructed','traced_fraction':0,'sources':[spec['source']],
                           'segments':[{'how':'map_corridor_reconstruction','note':spec['track_note']}],
                           'left_off_embankment_face_s':[]})
        extension[side]=tracks
    ground.doc=doc
    # Record the rail envelope alongside the mapped coast for inspection.
    for side in ('north','south'):
        for k,p in enumerate(extension[side][0]['centreline_local_m']):
            es=[t['centreline_local_m'][k][0] for t in extension[side]]
            doc['rail_bounds'].append([p[1],round(min(es)-8,2),round(max(es)+8,2)])
    doc['rail_bounds'].sort()
    combined=json.loads(json.dumps(base))
    combined.update({'_doc':'GENERATED by tools/extend_ic_lakefront_1904.py: original Sanborn core plus Talbot 1904 map context. Individual outer tracks and grades are reconstructed.',
                     'extended_by':'T-2495','extension_liberty':spec['liberty'], 'context_from':'data/terrain/epochs/e1871_postfire/context_spec.json'})
    combined['sources']=base['sources']+[spec['source']]
    combined['tracks']=base['tracks']+extension['north']+extension['south']
    def bands(side):
        tracks=extension[side]; line=doc[side]['shoreline_local_m']
        out={k:[] for k in ('cinders','west','east','made_ground','face','crest')}
        for i,(_,n) in enumerate(line):
            es=[t['centreline_local_m'][i][0] for t in tracks]
            west,east=min(es)-4,max(es)+3
            water=interp(line,n)
            # The profile's crest stands ~6 m inland, varying with the inherited grade.
            crest=water-1.5*ground.sample(water-20,n)
            east=min(east,crest-4)
            out['cinders'].append([west,n,east,n])
            out['west'].append([west-3,n,west,n])
            out['east'].append([east,n,east+3,n])
            # Past Twelfth Street the railway is inland of Grant Park's fill.
            # Do not pave that entire park in railway cinders.
            out['made_ground'].append([east+2.2,n,min(crest,east+18),n])
            out['face'].append([water+1.5,n,crest,n]);out['crest'].append([crest,n])
        return out
    bn,bs=bands('north'),bands('south')
    for k in ('cinders','made_ground'):
        combined['right_of_way'][k]=bn[k][:-1]+base['right_of_way'][k]+bs[k][1:]
    for i,k in enumerate(('west','east')):
        combined['right_of_way']['verges'][i]['stations']=bn[k][:-1]+base['right_of_way']['verges'][i]['stations']+bs[k][1:]
    for k in ('face','crest'):
        combined['lake_edge'][k]=bn[k][:-1]+base['lake_edge'][k]+bs[k][1:]
    return doc,combined,ground


def apron_glb(ground):
    """Engine-neutral indexed GLB; the detailed core is retained by the renderer."""
    m=ground.meta; margin=m['skirt']['margin_m']; step=10.0
    pos=[];indices=[]
    def strip(rows,cols):
        start=len(pos)
        for n in rows:
            shift=ground.shift(n)
            for e in cols:
                moved=e+shift if ground.e0<=e<=ground.e1 else e
                pos.append([moved,ground.sample(moved,n),-n])
        width=len(cols)
        for r in range(len(rows)-1):
            for c in range(width-1):
                a=start+r*width+c;b=a+1;d=a+width;e=d+1
                indices.extend([a,b,d,b,e,d])
    cols=[ground.e0-margin]+list(np.linspace(ground.e0,ground.e1,m['cols']))+[ground.e1+margin]
    for side in ('south','north'):
        line=ground.doc[side]['shoreline_local_m']; boundary=ground.doc[side]['join_n']
        rows=sorted(set([p[1] for p in line]+[boundary-margin if side=='south' else boundary+margin]))
        strip(rows,cols)
    ns=np.linspace(ground.n0,ground.n1,m['rows'])
    strip(ns,[ground.e0-margin,ground.e0]);strip(ns,[ground.e1,ground.e1+margin])
    p=np.array(pos,dtype='<f4');ix=np.array(indices,dtype='<u4')
    # Sample at the float32 plan position the GLB actually delivers, including
    # steep plan bends at the mapped pier edges; do not bank pre-rounding heights.
    for point in p:
        point[1] = ground.sample(float(point[0]), -float(point[2]))
    # Smooth normals from the same triangles, including the sloped shore face.
    norms=np.zeros_like(p)
    tris=ix.reshape(-1,3); normal=np.cross(p[tris[:,1]]-p[tris[:,0]],p[tris[:,2]]-p[tris[:,0]])
    for k in range(3):np.add.at(norms,tris[:,k],normal)
    norms/=np.maximum(np.linalg.norm(norms,axis=1)[:,None],1e-12)
    arrays=[p,norms,np.ones((len(p),1),dtype='<f4'),ix]
    views=[];access=[];binary=b''
    for i,a in enumerate(arrays):
        raw=a.tobytes();views.append({'buffer':0,'byteOffset':len(binary),'byteLength':len(raw)})
        ac={'bufferView':i,'componentType':5125 if i==3 else 5126,'count':len(a),'type':'SCALAR' if i>=2 else 'VEC3'}
        if i==0:ac.update({'min':p.min(axis=0).tolist(),'max':p.max(axis=0).tolist()})
        access.append(ac);binary+=raw
    gl={'asset':{'version':'2.0','generator':'tools/extend_ic_lakefront_1904.py'},'buffers':[{'byteLength':len(binary)}],
        'bufferViews':views,'accessors':access,'meshes':[{'name':'1904_context_ground','primitives':[{'attributes':{'POSITION':0,'NORMAL':1,'_CONFIDENCE':2},'indices':3}]}],
        'nodes':[{'mesh':0}],'scenes':[{'nodes':[0]}],'scene':0}
    js=json.dumps(gl,separators=(',',':')).encode();js+=b' '*((-len(js))%4)
    return struct.pack('<4sII',b'glTF',2,28+len(js)+len(binary))+struct.pack('<I4s',len(js),b'JSON')+js+struct.pack('<I4s',len(binary),b'BIN\0')+binary


def validate(doc,rail,ground):
    base=json.loads((ROOT/'data/railway/1904.json').read_text())
    assert rail['tracks'][:len(base['tracks'])]==base['tracks'],'detailed tracks changed'
    for side,idx in [('north',0),('south',-1)]:
        ts=[t for t in rail['tracks'] if t['id'].endswith('_'+side)]
        boundary=doc[side]['join_n'];end=doc['map_n_m'][1 if side=='north' else 0]
        for t in ts:
            parent=next(b for b in base['tracks'] if b['id']==t['connects_to'])
            assert t['centreline_local_m'][-1 if side=='north' else 0]==parent['centreline_local_m'][idx],t['id']+' disconnected'
            assert abs(t['centreline_local_m'][0 if side=='north' else -1][1]-end)<.001
            for e,n in t['centreline_local_m']:
                assert ground.sample(e,n)>1,t['id']+' in water'
                assert ground.sample(e,n)>=ground.sample(e-8,n)-.3,t['id']+' on shore face'
        for e in np.arange(ground.e0,ground.e1+1,2.5):
            assert abs(ground.sample(e,boundary)-ground.sample(e,boundary+(0.00001 if side=='north' else -0.00001)))<.001,'ground join'
    assert all((ROOT/'data/sources'/f'{s}.json').exists() for s in rail['sources'])


def main():
    doc,rail,ground=build();validate(doc,rail,ground)
    products={OUT:dumps(doc).encode(),RAIL:dumps(rail).encode(),GLB:apron_glb(ground)}
    bad=[]
    for p,b in products.items():
        if '--check' in sys.argv:
            if not p.exists() or p.read_bytes()!=b:bad.append(str(p.relative_to(ROOT)))
        else:p.write_bytes(b)
    if bad:raise SystemExit('FAIL stale: '+', '.join(bad))
    print('OK 1904 outer lakefront: connected tracks, map extents, dry rail beds, terrain seams; '+('outputs match' if '--check' in sys.argv else 'generated'))

if __name__=='__main__':main()
