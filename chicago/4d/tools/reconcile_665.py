def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def group_of(family: str) -> str:
    if family.startswith("A"):
        return "barns_stables" if family in ("A1", "A2") else "small_outbuildings"
    return GROUP_OF_LETTER[family[0]]


def apportion(total: int, weights: list[float]) -> list[int]:
    """Hamilton's method — proportional, integer, sums exactly, ties broken by position."""
    if total <= 0 or not weights:
        return [0] * len(weights)
    mass = sum(weights)
    if mass <= 0:
        out = [0] * len(weights)
        out[0] = total
        return out
    exact = [total * w / mass for w in weights]
    out = [int(x) for x in exact]
    order = sorted(range(len(weights)), key=lambda i: (-(exact[i] - out[i]), i))
    for i in order[: total - sum(out)]:
        out[i] += 1
    return out


def deal(counts: dict[str, int]) -> list[str]:
    """A deterministic mixed deal: each family's tokens are spread evenly over the whole
    run, so dealing the run to units in order gives every unit the district's mix rather
    than one family per block."""
    total = sum(counts.values())
    tokens = []
    for family, n in sorted(counts.items()):
        for i in range(n):
            tokens.append((((i + 0.5) * total) / n, family))
    tokens.sort(key=lambda t: (t[0], t[1]))
    return [family for _, family in tokens]


# ---- the business-front term (T-0213) --------------------------------------------
#
# The schedule apportions families by DISTRICT and has no notion of a street. Measured on
# the committed record, that is wrong in one particular: the DOCUMENTED trade share is
# monotone in the committed street hierarchy — 0.7778 of the documented buildings standing
# nearest a `principal` street carry a trade family, 0.4545 on an `ordinary` street and
# 0.0000 on a `light` one (`tools/measure_frontage_fabric.py --trade`, 68 records). So a
# block dealt a South Water face should be likelier to be dealt C, F and W than a block two
# streets back, and until this term it was not: `blk_south_water_franklin` and
# `blk_south_water_lasalle` between them held twelve of the business front's roofs and not
# one of them was a store, a warehouse or a workshop.
#
# What this is NOT. It does not raise or lower the target, it does not move a roof between
# districts, and it does not change how many roofs any unit is dealt. It is a PERMUTATION
# of the principal families a district's platted blocks were already dealt, among those
# same blocks — so every marginal that closed before it closes after it, by construction
# rather than by a check. The proof is cheap and it is asserted below.
#
# It reads only the RESEARCH layer, which is the part that makes it a measurement rather
# than a feedback loop: weighting the schedule by what the schedule invented would be the
# programme grading its own homework, and the share would ratchet with every block built.


def is_trade(family: str) -> bool:
    """C stores, F warehouses, W workshops — the letters the trade share was measured on.

    Imported from the census rather than restated here, so the weight and the measurement
    it is derived from cannot come to disagree about what a trade building is.
    """
    return family[0] in TRADE_LETTERS


def frontage_weight(bounded_by: dict, shares: dict, traffic: dict) -> float:
    """A block's expected trade share, read off the streets that bound it.

    Every face of a platted block is a committed street carrying a committed traffic class,
    and the documented record gives each class its own trade share. A block's weight is the
    mean of its own four faces' shares — a South Water block has two principal faces of
    four, a Randolph block has none — so the schedule tells them apart without anybody
    typing a number for either. Re-class a street on `data/streets/1835.json` and every
    block on it re-weights in the same commit.

    A face whose class the documented record says nothing about takes the mean of the
    classes it does speak for, so an unmeasured street neither promotes nor demotes a block.
    """
    if not bounded_by:
        return 0.0
    measured = [row["share"] for row in shares.values()]
    fallback = sum(measured) / len(measured) if measured else 0.0
    faces = [shares[traffic[street]]["share"]
             if traffic.get(street) in shares else fallback
             for street in bounded_by.values()]
    return sum(faces) / len(faces)


def _fit(quota: list[int], slots: list[int], weights: list[float]) -> list[int]:
    """Hamilton's quota, clipped to the slots each unit actually has.

    A weight says how MUCH of the trade a block should attract; it cannot say the block has
    room for it. Overflow is re-apportioned over the blocks that still have a principal slot
    free, at their own weights, until it fits — and it always fits, because the tokens being
    placed came out of these same slots.
    """
    quota = list(quota)
    while True:
        excess = sum(max(0, q - s) for q, s in zip(quota, slots))
        if not excess:
            return quota
        free = [i for i, (q, s) in enumerate(zip(quota, slots)) if q < s]
        quota = [min(q, s) for q, s in zip(quota, slots)]
        if not free:
            raise SystemExit("business front: more trade roofs than principal slots")
        for i, extra in zip(free, apportion(excess, [weights[i] for i in free])):
            quota[i] += extra


def weight_the_business_front(units: list[dict], shares: dict,
                              traffic: dict) -> list[dict]:
    """Re-deal each district's PRINCIPAL families across its platted blocks by frontage.

    Only units with a `bounded_by` take part: a district balance and the West recipe
    remainder stand on no committed street at all, so there is nothing to weight them by
    and they keep exactly what the district deal gave them.

    Returns one row per district that moved, for the ledger.
    """
    moved = []
    for district in DISTRICTS:
        blocks = [u for u in units
                  if u["district"] == district and u.get("bounded_by") and u.get("roofs")]
        if len(blocks) < 2:
            continue
        pool: dict[str, int] = {}
        slots: list[int] = []
        before: list[dict[str, int]] = []
        for unit in blocks:
            count = 0
            for family, n in unit["families"].items():
                if group_of(family) in ANCILLARY_GROUPS:
                    continue
                pool[family] = pool.get(family, 0) + n
                count += n
            slots.append(count)
            before.append(dict(unit["families"]))
        trade_total = sum(n for f, n in pool.items() if is_trade(f))
        if not trade_total or trade_total == sum(slots):
            continue

        weights = [n * frontage_weight(u["bounded_by"], shares, traffic)
                   for n, u in zip(slots, blocks)]
        quota = _fit(apportion(trade_total, weights), slots, weights)

        trade = deal({f: n for f, n in pool.items() if is_trade(f)})
        other = deal({f: n for f, n in pool.items() if not is_trade(f)})
        changed = 0
        for index, unit in enumerate(blocks):
            take = trade[:quota[index]] + other[:slots[index] - quota[index]]
            trade, other = trade[quota[index]:], other[slots[index] - quota[index]:]
            mix = {f: n for f, n in unit["families"].items()
                   if group_of(f) in ANCILLARY_GROUPS}
            for family in take:
                mix[family] = mix.get(family, 0) + 1
            unit["families"] = {f: mix[f] for f in sorted(mix)}
            unit["frontage_weight"] = round(
                frontage_weight(unit["bounded_by"], shares, traffic), 4)
            unit["trade_roofs"] = quota[index]
            changed += unit["families"] != before[index]
        if trade or other:
            raise SystemExit(f"{district}: business front left {len(trade) + len(other)} "
                             "principal roofs unplaced")

        # The permutation is the whole safety argument, so it is asserted rather than
        # trusted: the same families, the same count in every block, the same trade total.
        after: dict[str, int] = {}
        for unit in blocks:
            for family, n in unit["families"].items():
                after[family] = after.get(family, 0) + n
        combined: dict[str, int] = {}
        for row in before:
            for family, n in row.items():
                combined[family] = combined.get(family, 0) + n
        if after != combined:
            raise SystemExit(f"{district}: the business-front deal is not a permutation")
        for unit, count in zip(blocks, slots):
            got = sum(n for f, n in unit["families"].items()
                      if group_of(f) not in ANCILLARY_GROUPS)
            if got != count:
                raise SystemExit(f"{unit['id']}: dealt {got} principal roofs against "
                                 f"{count} before the business-front term")
        moved.append({"district": district, "blocks": len(blocks),
                      "trade_roofs": trade_total, "blocks_redealt": changed,
                      "quota": {u["id"]: q for u, q in zip(blocks, quota)}})
    return moved


# ---- the waterside term (T-0316) -------------------------------------------------
#
# THE PLAT IS NOT GROUND A LANDING APRON CAN STAND ON, AND THAT IS A FACT ABOUT THE
# GENERATOR RATHER THAN ABOUT ANY ONE BLOCK.
#
# `tools/generate_block_infill.py` authors no coordinates. Every metre it places comes
# from a committed lot polygon inside a block bounded by four platted STREETS, and the
# wharf and landing ground of the main stem lies outside that grid entirely — it is
# placed by `tools/generate_river_wharves.py` against the committed bank. So a family
# whose own crosswalk record makes water access a PRECONDITION OF THE FORM cannot be
# built by the parcel that builds platted blocks, at any distance: even on a block whose
# own face is a river street, the apron would have to cross a public one.
#
# T-0028 found this on 2026-08-28 by opening `blk_lake_franklin` and being unable to
# build the F3 it had been dealt, 134 m from the nearest water. The stopgap was to put
# F3 in the block generator's `REFUSED_FAMILIES`, so a recipe meeting the slot DEFERS it
# with a stated reason (L203) rather than reaching for a shape. That keeps the roof on
# the books, and it treats a fault in the DEAL as a fault at the block: every future
# platted block dealt an F3 defers it, and the deferrals accumulate. T-0316 moves the
# repair upstream, which is T-0213's shape — weight the deal, do not teach each block to
# refuse.
#
# IT IS A PERMUTATION, exactly as the business front is: a waterside roof on a platted
# block is exchanged for a principal roof of the same trade-ness sitting in that
# district's own unbounded balance — the ground beyond committed control, which is where
# the wharf and landing ground is. No total moves: not the target, not a district, not a
# family, not any unit's roof count, not its principal/ancillary split. A district with
# no unbounded partner to swap with HOLDS the roof and says so, because a deal that
# quietly dropped it would be worse than the fault.

# The words that make a crosswalk entry a CANDIDATE for the waterside rule. Read off the
# record's `required_variant` and its `variants` line, which is where the form lives.
WATERSIDE_CANDIDATE_WORDS = ("river", "landing", "dock", "wharf", "quay")

# ...and the judgement on each candidate, which the keyword scan cannot make: whether
# the record's own assumption note states water access as a REQUIREMENT of the form or
# as a conditional variant. The note is quoted VERBATIM so that editing the record fails
# this derive rather than silently re-classifying a family — and a new candidate the
# crosswalk grows tomorrow fails it by name, unjudged, which is the point.
WATERSIDE_JUDGEMENT = {
    "F3": (True, "Landing apron and cargo-door arrangement must follow site access and "
                 "cannot extend into water or duplicate a counted pier."),
    "W5": (True, "A crane/derrick is rare and must not become a default; river access "
                 "requires validated dry-bank terrain contact."),
    # NOT waterside, and the record is what says so: the dock relationship is unknown for
    # an anonymous slot and the skids are conditional on the site, so an F1 dealt to a
    # platted block is a freight shed without skids rather than a form that cannot stand.
    # T-0316 was asked to check F1, F2 and F4 while it was here; F2 ("Hoist beam presence
    # varies; cargo type and operator are not inferred") and F4 ("Board-stack quantity and
    # open-side pattern are visual variation, not inventory facts") name no water at all
    # and are not candidates, so they are not listed — being absent from this table is
    # itself the statement, and the scan below is what keeps it true.
    "F1": (False, "Stored goods and dock relationship are not known for anonymous slots; "
                  "skids belong only where terrain and route access support them."),
}


def waterside_families() -> dict[str, str]:
    """The families the committed crosswalk makes waterside, and the sentence that says so.

    Two readings of the same record have to agree or this refuses to derive: the keyword
    scan says which families are even in question, and `WATERSIDE_JUDGEMENT` says which of
    those the record REQUIRES water for, quoting its own assumption note back at it.
    """
    crosswalk = load(DATA / "reconstruction" / "1835_family_archetype_crosswalk.json")
    seen: dict[str, str] = {}

    def walk(node):
        if isinstance(node, dict):
            if "id" in node and "label" in node and "required_variant" in node:
                hay = " ".join([
                    str(node.get("required_variant") or ""),
                    str((node.get("key_geometry_parameters") or {}).get("variants") or ""),
                ]).lower()
                if any(word in hay for word in WATERSIDE_CANDIDATE_WORDS):
                    seen[node["id"]] = str(node.get("assumption_note") or "").strip()
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(crosswalk)
    unjudged = sorted(set(seen) - set(WATERSIDE_JUDGEMENT))
    if unjudged:
        raise SystemExit(
            f"the crosswalk names water in the form of {', '.join(unjudged)} and "
            "tools/reconcile_665.py carries no judgement on them. Read each record's "
            "assumption_note and add it to WATERSIDE_JUDGEMENT — requiring water is a "
            "reading of the record, not of a keyword.")
    stale = sorted(set(WATERSIDE_JUDGEMENT) - set(seen))
    if stale:
        raise SystemExit(
            f"WATERSIDE_JUDGEMENT judges {', '.join(stale)}, which the crosswalk no "
            "longer names water in. The record moved; re-read it.")
    for family, (_, quoted) in sorted(WATERSIDE_JUDGEMENT.items()):
        if seen[family] != quoted:
            raise SystemExit(
                f"{family}: WATERSIDE_JUDGEMENT quotes an assumption note the crosswalk "
                "no longer carries. Re-read the record and re-make the judgement.\n"
                f"  crosswalk: {seen[family]}\n  here:      {quoted}")
    return {f: q for f, (requires, q) in sorted(WATERSIDE_JUDGEMENT.items()) if requires}


def _take_one(unit: dict, family: str) -> None:
    unit["families"][family] -= 1
    if unit["families"][family] == 0:
        del unit["families"][family]


def _give_one(unit: dict, family: str) -> None:
    unit["families"][family] = unit["families"].get(family, 0) + 1
    unit["families"] = {f: unit["families"][f] for f in sorted(unit["families"])}


def keep_the_waterside_off_the_plat(units: list[dict], waterside: dict[str, str],
                                    shares: dict, traffic: dict) -> dict:
    """Exchange every waterside roof on a platted block for a principal roof on the
    district's own unbounded balance. See the block comment above."""
    swapped, held = [], []
    for district in DISTRICTS:
        blocks = [u for u in units
                  if u["district"] == district and u.get("bounded_by") and u.get("roofs")]
        balances = [u for u in units
                    if u["district"] == district and not u.get("bounded_by")
                    and u.get("roofs")]
        for unit in blocks:
            for family in sorted(f for f in unit["families"] if f in waterside):
                for _ in range(unit["families"][family]):
                    partner = None
                    # Same trade-ness first, so the business-front weighting this term
                    # runs after is left exactly where T-0213 put it; anything principal
                    # and dry after that, and the ledger says which rule was used.
                    for want_same_trade in (True, False):
                        for other in balances:
                            for candidate in sorted(other["families"]):
                                if candidate in waterside:
                                    continue
                                if group_of(candidate) in ANCILLARY_GROUPS:
                                    continue
                                if want_same_trade and is_trade(candidate) != is_trade(family):
                                    continue
                                partner = (other, candidate)
                                break
                            if partner:
                                break
                        if partner:
                            break
                    if partner is None:
                        held.append({
                            "unit": unit["id"], "family": family,
                            "why": f"{district} has no unbounded balance holding a dry "
                                   "principal roof to exchange, so the roof stays on the "
                                   "block and the block generator defers it (L203)",
                        })
                        continue
                    other, candidate = partner
                    _take_one(unit, family)
                    _give_one(unit, candidate)
                    _take_one(other, candidate)
                    _give_one(other, family)
                    swapped.append({
                        "family": family, "from": unit["id"], "to": other["id"],
                        "for": candidate,
                        "same_trade": is_trade(candidate) == is_trade(family),
                    })
            if unit.get("bounded_by"):
                unit["trade_roofs"] = sum(n for f, n in unit["families"].items()
                                          if is_trade(f))
                unit["frontage_weight"] = round(
                    frontage_weight(unit["bounded_by"], shares, traffic), 4)
    # The permutation is the safety argument, so it is asserted rather than trusted.
    for unit in units:
        if not unit.get("families"):
            continue
        roofs = sum(unit["families"].values())
        if roofs != unit["roofs"]:
            raise SystemExit(f"{unit['id']}: the waterside term changed a roof count")
        principal = sum(n for f, n in unit["families"].items()
                        if group_of(f) not in ANCILLARY_GROUPS)
        if principal != unit["principal"]:
            raise SystemExit(f"{unit['id']}: the waterside term moved an ancillary roof")
    stranded = sorted(f"{u['id']}.{f}" for u in units if u.get("bounded_by")
                      for f in u.get("families", {}) if f in waterside)
    if len(stranded) != len(held):
        raise SystemExit("the waterside term left a waterside family on a platted block "
                         f"without holding it: {', '.join(stranded)}")
    return {"swapped": swapped, "held": held}


def inside(point, polygon) -> bool:
    x, y = point
    hit = False
    j = len(polygon) - 1
    for i in range(len(polygon)):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def block_rooms(free_lots: int, headroom_roofs: int) -> tuple[int, int]:
    """(principal, ancillary) a block can actually take, from its FREE LOTS.

    A block's room was counted in roofs and nothing else until ROADMAP T-A6, and roofs
    are not what binds it. Three separate things do, and the schedule could see only the
    first:

    1. the town's own roof ratio — one principal per lot plus ancillary at 154:511 —
       less what already stands in the block. That is `headroom_roofs`, unchanged.
    2. **a principal roof needs a FREE LOT**, and a free lot carries up to
       `ROW_UNITS_PER_LOT` of them (T-0079): a party-line run is bounded by the metres of
       frontage it stands on, not by the conjectural side lines it crosses. A lot with
       somebody's house on it is not
       headroom, and `standing_roofs` cannot tell the difference: two roofs on one lot
       and two roofs on two lots subtract the same. Half the open blocks were being dealt
       principal roofs with nowhere to stand — `blk_south_water_clark` and
       `blk_lake_market` were dealt seven against six free lots, which no recipe could
       have written down, and three more were dealt exactly as many as they had free.
    3. **the block keeps one lot open.** The parcel recipe's own placement rule says so
       — "a block at capacity is a claim about 1835 that the evidence does not support;
       the schedule's capacity is a ceiling" — and until now that was a promise each
       parcel made by hand, which a block dealt exactly its free-lot count could not
       keep. A rule a parcel can be dealt out of is not a rule.

    And the ancillary count is bounded by the principal one, because the generator's
    yard-building gate is that an ancillary roof stands in the yard of a principal roof
    THIS parcel built. `blk_randolph_dearborn` was dealt one ancillary and no principal,
    so its backfill (T-A3h) was unbuildable for that reason rather than this one — the
    same blindness, seen from the other end.
    """
    principal = max(0, min(ROW_UNITS_PER_LOT * (free_lots - 1), headroom_roofs))
    ancillary = min(round(principal * ANCILLARY_PER_PRINCIPAL), headroom_roofs - principal)
    return principal, max(0, ancillary)


def lot_ceiling_principal(free_lots: int) -> int:
    """The principal roofs a block can carry with NO party-line row on it (T-0834).

    One principal roof per lot is what `tools/generate_block_infill.py` admits of an
    ordinary roof — it stands ON a lot, carries that lot's `lot_index`, and the gate
    that refuses two roofs on one lot is the same one T-0105 wrote — and the block
    keeps one lot open, clause 3 of `block_rooms`. So a block with no frontage run can
    hold `free_lots - 1` principal roofs and not one more.
    """
    return max(0, free_lots - 1)


def row_lots_required(free_lots: int, principal: int) -> int:
    """The fewest lots of FRONTAGE a block's run must be dealt for the principal roofs
    it was dealt to have anywhere to stand (T-0834).

    THE TWO SIZINGS THIS RECONCILES, because for a year they were two numbers in two
    files with nothing tying them together. `block_rooms` sizes principal room at
    `ROW_UNITS_PER_LOT` party-line units per free lot; the generator places by whole
    LOTS and admits the party-line density only along a frontage run the recipe names
    and gates at `ROW_UNITS_PER_LOT * len(frontage["lots"])`. A block that gives its
    run k of its free lots therefore holds

        (free_lots - k - 1)  +  ROW_UNITS_PER_LOT * k
            =  free_lots - 1  +  k * (ROW_UNITS_PER_LOT - 1)

    principal roofs — one on each free lot the run did not take, less the lot the block
    keeps open, plus the run's own units — and `principal_room` is exactly that
    expression at k = free_lots - 1, its maximum. So the schedule was never wrong about
    the metres and never said what it was assuming: its sizing is CONDITIONAL on a row
    across nearly the whole block, and until T-0834 the condition lived only in the
    prose of whichever recipe happened to meet it. On `blk_south_water_clark`'s second
    deal — the block that found this, T-0431 — 2 free lots sized 3 principal roofs, the
    deal gave it 1, and the run it named was headroom rather than necessity: k_min is 0
    there. On `blk_south_water_franklin`'s second deal the same 2 free lots were dealt
    3, so k_min is 1 and the run it named was the only ground those roofs had. Two
    parcels that read identically in the ledger, told apart by a number.

    Inverting the expression for the smallest k that holds `principal`:

        k >= (principal - free_lots + 1) / (ROW_UNITS_PER_LOT - 1)

    Returns 0 where the lots alone suffice. A block whose k_min exceeds its free lots
    less one has been dealt more than any arrangement of it can stand, which is the
    over-deal `block_rooms` already refuses upstream; this states it rather than
    trusting that it cannot happen.
    """
    if ROW_UNITS_PER_LOT <= 1:
        return 0
    short = principal - lot_ceiling_principal(free_lots)
    if short <= 0:
        return 0
    return -(-short // (ROW_UNITS_PER_LOT - 1))


def standing_roofs(grid, datum, taken):
    """Every committed structure record, with the physical roofs it puts in the scene and
    the platted block it stands in, where the grid reaches it.

    **A roof standing on a block's lot stands in that block**, which is the second half
    of the T-A7 finding. The block was read off the record's position POINT against the
    block boundary, and a building placed a metre proud of its own frontage has that
    point in the roadway: the Exchange Coffee House holds nine tenths of a lot of
    `blk_south_water_franklin` and was counted as standing in no block at all. Its
    roof was therefore not subtracted from the headroom of the block it stands in, so
    the schedule offered that block room a visitor can see is already built on. The
    occupancy map — derived from the footprint, in `tools/plat_occupancy.py` — answers
    it where the point cannot.
    """
    home = block_of_structure(taken)
    reconciliation = {
        r["structure_id"]: r
        for r in load(RECON / "1835_existing_roof_reconciliation.json")["records"]
    }
    households = {
        b["id"]: b
        for b in load(RECON / "1835_inferred_household_programme.json")["buildings"]
    }
    rows = []
    for path in sorted((DATA / "structures").glob("*.json")):
        record = load(path)
        rid = record["id"]
        # WHICH PROGRAMME RAISED THIS ROOF, not merely whether it discloses a family
        # band. Both answers used to be the same question, because only the anonymous
        # generators wrote a reconstruction block. Since K21 the inferred-household
        # layer's 31 buildings carry one too — they are drawn from the same family
        # bands and now say so in a field — and a bare `"reconstruction" in record`
        # test moved all 31 out of `inferred_household_programme` and into
        # `generated`. The totals were unchanged, which is exactly why it is worth a
        # gate's attention: the ledger would have gone on reporting 665 roofs while
        # crediting a third of the household layer to a generator that never ran.
        # T-0516. Two anonymous statuses now, and one of them was not dealt by a
        # generator. The owner retired the reconstructed resident population on
        # 2026-09-02 and ruled its roofs kept as anonymous stock, so the 31 buildings
        # this layer RAISED read `inferred_anonymous` like every parcel's count-unit —
        # and reading only the status would credit them to `generated`, which is the
        # same fault in the other direction as the one the paragraph above records: a
        # ledger reporting 665 roofs while crediting a thirty-first of the town to a
        # generator that never ran. The phase is what survives the status change, so
        # the phase is what separates them, and they enrol under their own source name
        # rather than disappearing into the parcels'.
        block = record.get("reconstruction") or {}
        if block.get("status") == "inferred_anonymous":
            retired = block.get("programme_phase") == "phase2_inferred_households"
            row = {"id": rid,
                   "source": "retired_household_roofs" if retired else "generated",
                   "district": block["district"],
                   "family": block["family"], "roofs_min": 1, "roofs_max": 1,
                   "programme_phase": block.get("programme_phase")}
        elif rid in reconciliation:
            entry = reconciliation[rid]
            count = entry["inventory_roof_count"] if entry["inventory_eligible"] else 0
            row = {"id": rid, "source": "pre_existing", "district": entry["district"],
                   "family": entry.get("likely_family"),
                   "roofs_min": count["min"] if isinstance(count, dict) else count,
                   "roofs_max": count["max"] if isinstance(count, dict) else count}
        elif rid in households:
            entry = households[rid]
            row = {"id": rid, "source": "inferred_household_programme",
                   "district": entry["district"], "family": entry["family"],
                   "roofs_min": 1, "roofs_max": 1}
        else:
            raise SystemExit(
                f"{rid} belongs to no programme this ledger can read. A structure record "
                "must carry a reconstruction block, or be an entry in the physical-roof "
                "reconciliation, or be a building of the inferred-household programme — "
                "otherwise it stands in the scene and not in the count."
            )
        if row["family"] is None and row["roofs_min"]:
            raise SystemExit(f"{rid} contributes a roof with no family to count it under")
        position = next((p["position"] for p in record["phases"]
                         if p.get("position") and p["position"].get("utm_e") is not None), None)
        row["block"] = home.get(rid)
        if row["block"] is None and position:
            point = (position["utm_e"] - datum["origin_utm_e"],
                     position["utm_n"] - datum["origin_utm_n"])
            for block in grid["blocks"]:
                if inside(point, block["boundary_local_enu_m"]):
                    row["block"] = block["id"]
                    break
        rows.append(row)
    return rows


def district_of_block(block) -> str:
    """A block is West Division ground when it lies west of the South Branch, which at
    this datum is local easting 0 — the origin IS the forks. No block in the grid
    straddles a division line."""
    return "west" if max(p[0] for p in block["boundary_local_enu_m"]) < 0 else "south"


