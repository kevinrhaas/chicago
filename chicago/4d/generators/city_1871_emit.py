        self.water_bounds=[(min(p[0] for p in w["polygon"])-10,max(p[0] for p in w["polygon"])+10,
                            min(p[1] for p in w["polygon"])-10,max(p[1] for p in w["polygon"])+10)
                           for w in self.water_polygons]
