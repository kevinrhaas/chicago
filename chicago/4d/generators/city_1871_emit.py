def inputs_sha():
    """One recipe stamp for all products; used by the repository's stale gate."""
    h = hashlib.sha256(b"city-context-1871-v1\0")
    for p in (Path(__file__), PLAN, ROOT / "data/datum.json"):
        h.update(p.relative_to(ROOT).as_posix().encode() + b"\0")
        h.update(p.read_bytes())
    return h.hexdigest()


def en(u, v):
    return (ANCHOR[0] + C*u - S*v, ANCHOR[1] + S*u + C*v)


def uv(e, n):
    x, y = e-ANCHOR[0], n-ANCHOR[1]
    return (C*x+S*y, -S*x+C*y)


def inside(p, polygon):
    x, y = p
    odd = False
    for a, b in zip(polygon, polygon[1:]+polygon[:1]):
        if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:
            odd = not odd
    return odd


def segdist(p, a, b):
    x, y = b[0]-a[0], b[1]-a[1]
    d = x*x+y*y
    t = max(0., min(1., ((p[0]-a[0])*x+(p[1]-a[1])*y)/d)) if d else 0.
    return math.hypot(p[0]-a[0]-t*x, p[1]-a[1]-t*y)


def distance(p, pts):
    return min(segdist(p, a, b) for a, b in zip(pts, pts[1:]))


def extent_uv(b):
    """A footprint's extent along the grid's (u, v) axes.

    T-3686: a front on a north-south street is turned a quarter, so its
    frontage (width_m) runs along v and its depth along u.
    """
    turned = abs(((b["bearing_deg"]+math.degrees(ANGLE)) % 180)-90) < 1
    return (b["depth_m"], b["width_m"]) if turned else (b["width_m"], b["depth_m"])


def intersection(a, b, c, d):
    ax, ay, bx, by = b[0]-a[0], b[1]-a[1], d[0]-c[0], d[1]-c[1]
    det = ax*by-ay*bx
    if abs(det) < 1e-8:
        return None
    x, y = c[0]-a[0], c[1]-a[1]
    t, u = (x*by-y*bx)/det, (x*ay-y*ax)/det
    if 0 <= t <= 1 and 0 <= u <= 1:
        return (a[0]+t*ax, a[1]+t*ay)
    return None


def bank_accuracy(city, sampler, spacing=40.):
    """Measure rendered zero waterline against the plan's modeled bank lines.

    This is sampling error, separate from the map's training/check residuals.
    Junctions with no isolated modeled bank are counted as excluded. Thin land
    missed by the field is counted as unresolved, rather than hidden in a mean.
    """
    samples=[]
    for a,b in zip(city.shore,city.shore[1:]):
        length=math.dist(a,b)
        if length<.01:continue
        normal=(-(b[1]-a[1])/length,(b[0]-a[0])/length)
        count=max(1,math.ceil(length/spacing))
        for i in range(count):
            t=(i+.5)/count
            samples.append(("shore",(a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t),normal))
    for river in city.rivers:
        for a,b in zip(river["points"],river["points"][1:]):
            length=math.dist(a,b)
            if length<.01:continue
            count=max(1,math.ceil(length/spacing))
            for i in range(count):
                t=(i+.5)/count
                for side in (-1,1):
                    normal=(-(b[1]-a[1])/length*side,(b[0]-a[0])/length*side)
                    point=(a[0]+(b[0]-a[0])*t+normal[0]*river.get("width_m",65)/2,
                           a[1]+(b[1]-a[1])*t+normal[1]*river.get("width_m",65)/2)
                    samples.append(("river",point,normal))
    for water in city.water_polygons:
        polygon=water["polygon"]
        if polygon[0]==polygon[-1]:polygon=polygon[:-1]
        area=sum(a[0]*b[1]-b[0]*a[1] for a,b in zip(polygon,polygon[1:]+polygon[:1]))
        for a,b in zip(polygon,polygon[1:]+polygon[:1]):
            length=math.dist(a,b)
            if length<.01:continue
            sign=1 if area>0 else -1
            normal=((b[1]-a[1])/length*sign,-(b[0]-a[0])/length*sign)
            count=max(1,math.ceil(length/spacing))
            for i in range(count):
                t=(i+.5)/count
                samples.append(("lagoon",(a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t),normal))
    groups={kind:{"errors":[],"plan_errors":[],"excluded":0,"unresolved":[]} for kind in ("shore","river","lagoon")}
    def root(fn,p,n,lo,hi):
        left=fn(p[0]+n[0]*lo,p[1]+n[1]*lo)
        for _ in range(16):
            mid=(lo+hi)/2;value=fn(p[0]+n[0]*mid,p[1]+n[1]*mid)
            if (value<0)==(left<0):lo=mid
            else:hi=mid
        return (lo+hi)/2
    for kind,p,n in samples:
        g=groups[kind]
        if not(BOUNDS[0]+35<p[0]<BOUNDS[1]-35 and BOUNDS[2]+35<p[1]<BOUNDS[3]-35):g["excluded"]+=1;continue
        if not(city.ground(p[0]-n[0]*.5,p[1]-n[1]*.5)<0<city.ground(p[0]+n[0]*.5,p[1]+n[1]*.5)):
            g["excluded"]+=1;continue
        analytic=root(city.ground,p,n,-.5,.5)
        readings=[(t,sampler(p[0]+n[0]*t,p[1]+n[1]*t)) for t in range(-30,31,2)]
        roots=[root(sampler,p,n,a[0],b[0]) for a,b in zip(readings,readings[1:]) if (a[1]<0)!=(b[1]<0)]
        if not roots:g["unresolved"].append([round(v,2) for v in p]);continue
        sampled=min(roots,key=lambda t:abs(t-analytic))
        g["errors"].append(abs(sampled-analytic));g["plan_errors"].append(abs(sampled))
    out={"method":"Stations every 40 m along modeled banks; closest zero contour within 30 m, measured perpendicular to each shoreline or riverbank. Riverbank widths remain reconstructed. Junction exclusions and unresolved thin land are reported separately.","spacing_m":spacing,"search_radius_m":30}
    for kind,g in groups.items():
        def stats(values):
            ordered=sorted(values)
            return {"mean_m":round(sum(values)/len(values),4),"p95_m":round(ordered[min(len(ordered)-1,int(len(ordered)*.95))],4),"max_m":round(max(values),4)} if values else None
        out[kind]={"sample_count":len(g["errors"]),"excluded_junction_or_extent_count":g["excluded"],"unresolved_count":len(g["unresolved"]),"unresolved_points":g["unresolved"],"resampling_error":stats(g["errors"]),"distance_from_modeled_plan_bank":stats(g["plan_errors"])}
    return out


class SpatialLines:
    """Small uniform index: per-lot exclusions never scan the whole city's roads."""
    def __init__(self, lines, cell=200):
        self.cell, self.bins = cell, collections.defaultdict(list)
        for line in lines:
            width = line.get("width_m", 20)/2 + line.get("walk_m", 3) + 3
            for a, b in zip(line["points"], line["points"][1:]):
                rec = (a, b, width)
                for i in range(math.floor((min(a[0], b[0])-width)/cell), math.floor((max(a[0], b[0])+width)/cell)+1):
                    for j in range(math.floor((min(a[1], b[1])-width)/cell), math.floor((max(a[1], b[1])+width)/cell)+1):
                        self.bins[i,j].append(rec)

    def clear(self, p, extra=0):
        # Insertion covers the base width. An added clearance can reach a
        # neighboring bin even when the point itself lies outside that width.
        return all(segdist(p,a,b)>w+extra
                   for i in range(math.floor((p[0]-extra)/self.cell),math.floor((p[0]+extra)/self.cell)+1)
                   for j in range(math.floor((p[1]-extra)/self.cell),math.floor((p[1]+extra)/self.cell)+1)
                   for a,b,w in self.bins[i,j])


class Mesh:
    """GLB mesh split by material and 500 m tile, so frustum culling stays useful."""
    PALETTE = {
        "earth": ([.33,.28,.17,1],1), "water": ([.10,.23,.24,1],.3),
        "woodblock": ([.31,.27,.21,1],.96), "dirt": ([.43,.35,.24,1],1),
        "plank": ([.52,.44,.32,1],.94), "stone": ([.47,.45,.40,1],.92),
        "iron": ([.15,.17,.16,1],.66), "ballast": ([.36,.34,.30,1],1),
        "timber": ([.30,.23,.16,1],.98), "sand": ([.59,.51,.37,1],1),
        "charred": ([.20,.18,.15,1],1),
    }

    def __init__(self, name, tiled=True):
        self.name, self.tiled = name, tiled
        self.parts = collections.defaultdict(lambda: {"p":[], "n":[], "uv":[], "i":[]})

    def face(self, mat, pts, layer=None):
        # points already use glTF axes; wind the face counterclockwise outside.
        tile = (math.floor(pts[0][0]/500), math.floor(-pts[0][2]/500)) if self.tiled else (0,0)
        q = self.parts[(layer or mat, mat, *tile)]
        a,b,c = pts[:3]
        u,v = [b[k]-a[k] for k in range(3)], [c[k]-a[k] for k in range(3)]
        normal = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        length = math.sqrt(sum(t*t for t in normal)) or 1
        normal = [t/length for t in normal]
        off = len(q["p"])
        q["p"].extend(pts); q["n"].extend([normal]*len(pts))
        q["uv"].extend([[p[0]/2, p[2]/2] for p in pts])
        for i in range(1,len(pts)-1): q["i"].extend([off,off+i,off+i+1])

    def ribbon(self, mat, a, b, width, y, layer=None):
        dx, dn = b[0]-a[0], b[1]-a[1]
        length = math.hypot(dx,dn)
        if length < .01: return
        if self.tiled and length>480:
            count=math.ceil(length/480)
            for i in range(count):
                aa=(a[0]+dx*i/count,a[1]+dn*i/count)
                bb=(a[0]+dx*(i+1)/count,a[1]+dn*(i+1)/count)
                self.ribbon(mat,aa,bb,width,y,layer)
            return
        x,n = -dn/length*width/2, dx/length*width/2
        self.face(mat, [(a[0]+x,y,-a[1]-n),(a[0]-x,y,-a[1]+n),
                        (b[0]-x,y,-b[1]+n),(b[0]+x,y,-b[1]-n)], layer)

    def box(self, mat, e, n, y0, width, depth, height, layer=None):
        x0,x1,z0,z1,y1=e-width/2,e+width/2,-n-depth/2,-n+depth/2,y0+height
        v=[(x0,y0,z0),(x1,y0,z0),(x1,y0,z1),(x0,y0,z1),
           (x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)]
        for ids in ([4,7,6,5],[0,1,2,3],[0,4,5,1],[1,5,6,2],[2,6,7,3],[3,7,4,0]):
            self.face(mat,[v[i] for i in ids],layer)

    def beam(self, mat, a, b, radius, layer):
        vec=[b[k]-a[k] for k in range(3)]; length=math.sqrt(sum(v*v for v in vec))
        if length < .01:return
        axis=[v/length for v in vec]
        ref=[0,1,0] if abs(axis[1])<.9 else [1,0,0]
        u=[axis[1]*ref[2]-axis[2]*ref[1],axis[2]*ref[0]-axis[0]*ref[2],axis[0]*ref[1]-axis[1]*ref[0]]
        ul=math.sqrt(sum(v*v for v in u));u=[v/ul*radius for v in u]
        v=[axis[1]*u[2]-axis[2]*u[1],axis[2]*u[0]-axis[0]*u[2],axis[0]*u[1]-axis[1]*u[0]]
        ring=lambda p:[[p[k]+i*u[k]+j*v[k] for k in range(3)] for i,j in [(1,1),(-1,1),(-1,-1),(1,-1)]]
        x,y=ring(a),ring(b)
        for i in range(4):self.face(mat,[x[i],x[(i+1)%4],y[(i+1)%4],y[i]],layer)

    def glb(self, digest):
        binary=bytearray();views=[];accessors=[];meshes=[];nodes=[];materials=[]
        images=[];textures=[]
        matids={}
        def texture(mat):
            """Small generated material tile: no external image or rights chain."""
            size=128;col=self.PALETTE[mat][0];pixels=bytearray()
            rng=random.Random("1871-material-"+mat)
            for y in range(size):
                pixels.append(0)
                for x in range(size):
                    grain=rng.uniform(.89,1.09)
                    if mat=="plank":
                        grain*=.57 if y%16<1 else .96+.07*math.sin(x*.34+y)
                    elif mat=="woodblock":
                        row=y//14;grain*=.64 if y%14<1 or (x+(row%2)*9)%18<1 else .91+((x//18+row*7)%5)*.04
                    elif mat=="ballast":grain*=.8+((x*7+y*11)%13)/35
                    for c in col[:3]:
                        linear=max(0,min(1,c*grain));srgb=12.92*linear if linear<=.0031308 else 1.055*linear**(1/2.4)-.055
                        pixels.append(round(srgb*255))
            def chunk(kind,data):return struct.pack(">I",len(data))+kind+data+struct.pack(">I",zlib.crc32(kind+data)&0xffffffff)
            png=b"\x89PNG\r\n\x1a\n"+chunk(b"IHDR",struct.pack(">IIBBBBB",size,size,8,2,0,0,0))+chunk(b"IDAT",zlib.compress(bytes(pixels),9))+chunk(b"IEND",b"")
            views.append({"buffer":0,"byteOffset":len(binary),"byteLength":len(png)});binary.extend(png);binary.extend(b"\0"*((-len(binary))%4))
            images.append({"name":"1871_procedural_"+mat,"mimeType":"image/png","bufferView":len(views)-1});textures.append({"sampler":0,"source":len(images)-1})
            return len(textures)-1
        def acc(values, kind, components, fmt="f"):
            flat=[x for value in values for x in (value if components>1 else (value,))]
            blob=struct.pack("<"+str(len(flat))+fmt,*flat)
            view={"buffer":0,"byteOffset":len(binary),"byteLength":len(blob),"target":34963 if fmt=="I" else 34962}
            binary.extend(blob); binary.extend(b"\0"*((-len(binary))%4));views.append(view)
            a={"bufferView":len(views)-1,"componentType":5125 if fmt=="I" else 5126,"count":len(values),"type":kind}
            if kind=="VEC3":
                f32=lambda v:struct.unpack("<f",struct.pack("<f",v))[0]
                a["min"]=[f32(min(v[k] for v in values)) for k in range(3)]
                a["max"]=[f32(max(v[k] for v in values)) for k in range(3)]
            accessors.append(a);return len(accessors)-1
        for (layer,mat,tx,ty),q in sorted(self.parts.items()):
            if not q["p"]:continue
            if mat not in matids:
                col,rough=self.PALETTE[mat];matids[mat]=len(materials)
                materials.append({"name":"1871_"+mat,"pbrMetallicRoughness":{"baseColorFactor":col,"roughnessFactor":rough,"metallicFactor":.45 if mat=="iron" else 0},"doubleSided":False})
                if mat in ("woodblock","plank","dirt","ballast","timber","charred"):
                    pbr=materials[-1]["pbrMetallicRoughness"];pbr["baseColorTexture"]={"index":texture(mat)};pbr["baseColorFactor"]=[1,1,1,1]
            primitive={"attributes":{"POSITION":acc(q["p"],"VEC3",3),"NORMAL":acc(q["n"],"VEC3",3),"TEXCOORD_0":acc(q["uv"],"VEC2",2),"_CONFIDENCE":acc([1.]*len(q["p"]),"SCALAR",1)},"indices":acc(q["i"],"SCALAR",1,"I"),"material":matids[mat]}
            name=f"{self.name}__{layer}__{tx}_{ty}"
            if self.name in ("terrain__e1871_prefire","water__e1871_prefire"):name=self.name
            meshes.append({"name":name,"primitives":[primitive]})
            nodes.append({"name":name,"mesh":len(meshes)-1,"extras":{"layer":layer,"confidence":"reconstructed","sources":SOURCES[:3],"liberty":LIBERTY}})
            if self.name in ("terrain__e1871_prefire","water__e1871_prefire"):nodes[-1]["extras"]["terrain_epoch"]="e1871_prefire"
        doc={"asset":{"version":"2.0","generator":GENERATOR,"extras":{"inputs_sha256":digest,"target_date":"1871-10-08"}},"scene":0,"scenes":[{"nodes":list(range(len(nodes)))}],"nodes":nodes,"meshes":meshes,"materials":materials,"accessors":accessors,"bufferViews":views,"buffers":[{"byteLength":len(binary)}]}
        if images:doc.update(images=images,textures=textures,samplers=[{"magFilter":9729,"minFilter":9987,"wrapS":10497,"wrapT":10497}])
        js=json.dumps(doc,separators=(",",":"),sort_keys=True).encode();js+=b" "*((-len(js))%4)
        return struct.pack("<III",0x46546c67,2,28+len(js)+len(binary))+struct.pack("<II",len(js),0x4e4f534a)+js+struct.pack("<II",len(binary),0x004e4942)+binary


